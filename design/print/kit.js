#!/usr/bin/env node
/* kit.js — writes what kits/warrant-mpl reads, so the Python kit never retypes a value.
   design/print/ · cert-machine (2026-10-29)

   The matplotlib kit is for people who will never run this repository (UFSC LabECO works in Python), so it carries
   its own copy of the register. A copy typed by hand is the drift the corpus.js lesson names; this one is GENERATED
   from the sources and checked against them:

     kits/warrant-mpl/warrant_mpl/register.json      the print register (design/print/tokens.js), the dash patterns and
                                                      the small-width rule (design/grammar.js), the legend's words and
                                                      the premise ladder's (playground/warrant.js), with their sha256
     kits/warrant-mpl/warrant_mpl/warrant-print.mplstyle   matplotlib's rcParams from the register, colour
     kits/warrant-mpl/warrant_mpl/warrant-grey.mplstyle    the same, every colour its greyscale value
     kits/warrant-mpl/examples/data/*.json           the README's three examples' numbers, extracted from OUR records
                                                      (certs/hseva-ledger.json, certs/ecbench-ledger.json and the
                                                      pinned corpus, certs/gsm8k-ledger.json), each with its source's
                                                      sha256

   usage: node design/print/kit.js           write them
          node design/print/kit.js --check   exit 1 if any is stale (the kit's test runs this inside the repository)
   MIT licensed. Part of cert-machine. */
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..', '..');
const G = require(path.join(ROOT, 'design', 'grammar.js'));
const W = require(path.join(ROOT, 'playground', 'warrant.js'));
const PR = require(path.join(__dirname, 'tokens.js'));
const KIT = path.join(ROOT, 'kits', 'warrant-mpl');
const sha = (rel) => crypto.createHash('sha256').update(fs.readFileSync(path.join(ROOT, rel))).digest('hex');
const J = (rel) => JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
const die = (m) => { console.error('kit: ' + m); process.exit(1); };

/* ------------------------------------------------------------ register.json -- */
function register() {
  const tokens = {};
  for (const t of PR.REGISTER) tokens[t.name.replace(/^--/, '')] = { hex: t.hex, grey: PR.mono(t.hex), kind: t.kind, grade: t.grade, status: t.status, shape: t.shape || null, role: t.role };
  return {
    what: 'The WARRANT print register for matplotlib. GENERATED by design/print/kit.js in cert-machine from the files named in `sources`; do not edit. A PROPOSAL (2026-10-29): see design/print/PROPOSAL.md.',
    sources: Object.fromEntries(['design/print/tokens.js', 'design/grammar.js', 'playground/warrant.js', 'design/tokens.js'].map((r) => [r, sha(r)])),
    patterns: { CLAIM: G.CLAIM, CLAIM_SM: G.CLAIM_SM, PICK: G.PICK, PICK_SM: G.PICK_SM, GUIDE: G.GUIDE, PERMITTED: G.PERMITTED, SMALL_BELOW: G.SMALL_BELOW },
    line_pt: PR.LINE_PT,
    tokens,
    standings: PR.STANDINGS.map((s) => ({ standing: s.standing, token: s.token ? s.token.replace(/^--/, '') : null,
      pattern: s.standing === 'COMPUTED' ? 'CLAIM' : s.standing === 'CHOSEN' ? 'PICK' : null, cap: s.cap || 'butt',
      void: s.void ? { hatch: s.void.hatch.replace(/^--/, ''), edge: s.void.edge.replace(/^--/, ''), glyph: s.void.glyph } : null })),
    guide: { token: PR.GUIDE.token.replace(/^--/, ''), pattern: 'GUIDE' },
    identity: PR.IDENTITY.map((i) => ({ token: i.token.replace(/^--/, ''), marker: i.marker, glyph: i.glyph, fallback: i.fallback ? i.fallback.replace(/^--/, '') : null })),
    ramp: PR.RAMP.map((n) => n.replace(/^--/, '')),
    legend: W.LEGEND.map((L) => ({ standing: W.NAME[L.s], label: L.label, gloss: L.gloss })),
    grades: W.GRADE.map((g, i) => ({ word: g, gloss: W.GRADE_GLOSS[i] })),
  };
}

/* ------------------------------------------------------------- the styles ---- */
function style(mode) {
  const c = (n) => (mode === 'grey' ? PR.mono(PR.hex(n)) : PR.hex(n)).replace('#', '');
  const cyc = PR.IDENTITY.map((i) => "'" + c(i.token) + "'").join(', ');
  const [d0, d1] = G.CLAIM.split(' '), [p0, p1] = G.PICK.split(' ');
  return [
    '# warrant-' + (mode === 'grey' ? 'grey' : 'print') + '.mplstyle: the WARRANT print register for matplotlib' + (mode === 'grey' ? ', every colour its greyscale value (CIE Y)' : '') + '.',
    '# GENERATED by design/print/kit.js in cert-machine from design/print/tokens.js and design/grammar.js; do not edit.',
    '# Ink on white paper. Dashes carry standing and are never scaled by line width (lines.scale_dashes: False), so a',
    '# figure emits only the patterns design/grammar.js permits. Use the helpers in warrant_mpl for standings.',
    'figure.facecolor: ' + c('--paper'), 'figure.edgecolor: ' + c('--paper'),
    'savefig.facecolor: ' + c('--paper'), 'savefig.edgecolor: ' + c('--paper'), 'savefig.transparent: False',
    'axes.facecolor: ' + c('--paper'), 'axes.edgecolor: ' + c('--ink-3'), 'axes.linewidth: 0.6',
    'axes.labelcolor: ' + c('--ink'), 'axes.titlecolor: ' + c('--ink'), 'axes.titlesize: 9', 'axes.labelsize: 8',
    'axes.spines.top: False', 'axes.spines.right: False', 'axes.grid: False', 'axes.axisbelow: True',
    'axes.prop_cycle: cycler(\'color\', [' + cyc + '])',
    'grid.color: ' + c('--grid'), 'grid.linewidth: 0.4', 'grid.linestyle: -', 'grid.alpha: 1.0',
    'xtick.color: ' + c('--ink-3'), 'ytick.color: ' + c('--ink-3'), 'xtick.labelcolor: ' + c('--ink-3'), 'ytick.labelcolor: ' + c('--ink-3'),
    'xtick.major.width: 0.6', 'ytick.major.width: 0.6', 'xtick.minor.width: 0.4', 'ytick.minor.width: 0.4',
    'xtick.labelsize: 7', 'ytick.labelsize: 7',
    'text.color: ' + c('--ink'),
    'lines.linewidth: ' + PR.LINE_PT, 'lines.color: ' + c('--ink'), 'lines.scale_dashes: False',
    'lines.dashed_pattern: ' + d0 + ', ' + d1, 'lines.dotted_pattern: ' + p0 + ', ' + p1,
    'lines.markeredgewidth: 0.8', 'lines.markersize: 5',
    'patch.edgecolor: ' + c('--ink'), 'patch.facecolor: ' + c('--ink'), 'patch.force_edgecolor: False',
    'hatch.color: ' + c('--guide'), 'hatch.linewidth: 0.6',
    'legend.frameon: False', 'legend.fontsize: 7', 'legend.framealpha: 1.0', 'legend.edgecolor: ' + c('--grid'), 'legend.facecolor: ' + c('--paper'),
    'font.family: sans-serif', 'font.sans-serif: Inter, Helvetica Neue, Arial, DejaVu Sans', 'font.size: 8',   /* warrant_mpl.use() narrows this to the installed faces, as a fallback chain */
    'mathtext.default: regular',
    'svg.fonttype: path', 'pdf.fonttype: 42', 'ps.fonttype: 42',
    'image.cmap: gray_r',
    '',
  ].join('\n');
}

/* --------------------------------------------------------- the examples' data -- */
function exampleData() {
  const H = J('certs/hseva-ledger.json'), E = J('certs/ecbench-ledger.json'), GS = J('certs/gsm8k-ledger.json');
  const A = H.buoys.A;
  const blocks = H.buoyBlocks.map((b) => {
    const B = A.blocks[b], r = B.rankings.ad;
    const fam = {};
    for (const f of ['expweibull', 'lognormal']) {
      const F = B.fits[f];
      fam[f] = F.certified ? { certified: true, levels: Object.fromEntries(Object.entries(F.returnLevel).map(([T, e]) => [T, [e.lo, e.hi]])),
        delta: B.stat && B.stat.fits[f] ? { 100: B.stat.fits[f].l100, 1000: B.stat.fits[f].l1000 } : null } : { certified: false };
    }
    return { block: b, n: B.n, verdict: r.verdict, pick: r.best || null, why: r.why || null, families: fam };
  });
  const buoy = { what: 'Buoy A (NDBC; the environmental-contour benchmark\'s dataset A): certified return levels of Hs, in metres, by block, for the two families Anderson–Darling picks on this buoy; each level an enclosure [lo, hi]; delta: the delta method\'s 95% interval (STATISTICAL, float: computed).',
    source: { record: 'certs/hseva-ledger.json', sha256: sha('certs/hseva-ledger.json'), generated: H.generated }, hours: A.n, years: A.years, largestHour: A.blocks.native.max,
    returnPeriods: H.returnPeriods, blocks, split: H.findings.buoys.disagree.find((d) => d.series === 'buoy A') || null };

  /* the 20-year contours of dataset A and the hours under them, counted exactly into 0.25 s × 0.2 m cells */
  const Lb = require(path.join(ROOT, 'instruments', 'ecbench', 'lib.js'));
  Lb.ensureCorpus();
  const pv = Lb.readDataset('datasets/A.txt'), rv = Lb.readDataset('datasets-retained/Ar.txt');
  const NX = 80, NY = 60, cells = new Array(NX * NY).fill(0);
  const intOf = (s) => { const [i, fr = ''] = s.split('.'); return { N: Number(i + fr), d: fr.length }; };
  for (const ds of [pv, rv]) for (let i = 0; i < ds.n; i++) {
    const u = intOf(ds.us[i]), h = intOf(ds.hs[i]);
    const ix = Math.floor(4 * u.N / 10 ** u.d), iy = Math.floor(5 * h.N / 10 ** h.d);
    if (ix >= NX || iy >= NY) die('an hour falls outside the 0–20 s × 0–12 m window');
    cells[iy * NX + ix]++;
  }
  const rows = ['1', '6', '3'].map((id) => E.rows.find((r) => r.dataset === 'A' && r.returnPeriod === 20 && r.contribution === id));
  const contours = rows.map((r) => {
    const K = Lb.readContour(r.file);
    if (K.sha256 !== r.sha256) die(r.file + ' does not match its pin');
    const c = E.comparisons.find((x) => x.contribution === r.contribution && x.returnPeriod === 20 && x.quantity === 'outside' && (x.dataset === 'A' || String(x.dataset).includes('A')));
    return { contribution: r.contribution, method: r.method, class: r.class, authors: r.authors, file: r.file, sha256: r.sha256,
      tz: K.pts.map((p) => p.u.s), hs: K.pts.map((p) => p.h.s), closed: r.polygon.closed, closingEdgeLength: r.polygon.closingEdgeLength,
      maxHs: r.polygon.maxHs, tzAtMaxHs: r.polygon.atMaxHs.u, outside: r.counts.full.out, printed: c ? c.printed : null };
  });
  const exp20 = E.expected.find((e) => e.dataset === 'A' && e.returnPeriod === 20);
  const contour = { what: 'Dataset A of the environmental-contour benchmark: three submitted 20-year contours (Tz, Hs as their files list them) and the hours they were scored on, counted exactly into chosen cells. outside: the exact count (decided); printed: the organizers\' float64 count (computed).',
    source: { record: 'certs/ecbench-ledger.json', sha256: sha('certs/ecbench-ledger.json'), generated: E.generated, datasets: { 'datasets/A.txt': pv.sha256, 'datasets-retained/Ar.txt': rv.sha256 }, commit: E.corpus.commit },
    hours: pv.n + rv.n, field: { tz: [0, 20, NX], hs: [0, 12, NY], counts: cells }, contours, expectedOutside: { total: exp20.total.exact, iform: [exp20.iform.lo, exp20.iform.hi] },
    largestHour: E.datasets.A.maxHs.full };

  const w = GS.test.rows.find((r) => r.i === 501);
  const gsm = { what: 'GSM8K test item 501: a step the answer key prints that does not hold as printed, and its exact value (the witness the cert-machine GSM8K report marks).',
    source: { record: 'certs/gsm8k-ledger.json', sha256: sha('certs/gsm8k-ledger.json') }, item: w.i, printed: { lhs: w.witness.lhs, rhs: w.witness.rhs }, exact: w.witness.exact, answer: w.answer };
  return { 'buoy-a.json': buoy, 'contours-a20.json': contour, 'gsm8k-501.json': gsm };
}

/* ------------------------------------------------------------------- run ---- */
function outputs() {
  const o = {};
  o['warrant_mpl/register.json'] = JSON.stringify(register(), null, 1) + '\n';
  o['warrant_mpl/warrant-print.mplstyle'] = style('print');
  o['warrant_mpl/warrant-grey.mplstyle'] = style('grey');
  for (const [f, d] of Object.entries(exampleData())) o['examples/data/' + f] = JSON.stringify(d) + '\n';
  return o;
}
if (require.main === module) {
  const check = process.argv.includes('--check');
  const o = outputs();
  let stale = 0;
  for (const [rel, text] of Object.entries(o)) {
    const p = path.join(KIT, rel);
    const cur = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    if (check) { if (cur !== text) { stale++; console.log('STALE  kits/warrant-mpl/' + rel); } else console.log('ok     kits/warrant-mpl/' + rel); continue; }
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, text);
    console.log('wrote  kits/warrant-mpl/' + rel + '  ' + Buffer.byteLength(text) + ' bytes');
  }
  if (check && stale) { console.log(stale + ' file(s) stale: run node design/print/kit.js'); process.exit(1); }
}
module.exports = { register, style, exampleData, outputs };
