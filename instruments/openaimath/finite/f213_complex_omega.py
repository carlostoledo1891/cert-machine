ZK = (18623, -2696, -2677, 194, 393, 17, 1, 8)
CC = {(0, 0): 8, (1, 0): 2, (0, 1): 2, (2, 0): -1, (0, 2): -1, (1, 1): -2}
_G = {}


def _tables(A, N, Qv):
    C = [[0] * (N - i + 1) for i in range(N + 1)]
    AW = [[[0] * (N - i + 1) for i in range(N + 1)] for _ in range(3)]
    for a_ in range(N + 1):
        for c_ in range(N - a_ + 1):
            v = A[a_][c_]
            C[a_][c_] = 72 * v + Qv * CC.get((a_, c_), 0)
            AW[0][a_][c_] = v * c_ * (c_ - 1)
            AW[1][a_][c_] = v * a_ * c_
            AW[2][a_][c_] = v * a_ * (a_ - 1)
    return C, AW


def _S(i, j, C, AW):
    """S_ij of eq. (cert:chart-rec): sum over 0 <= x < i, 0 <= y < j, (x,y) != (0,0) of C_xy A_ac w_h(a,c)"""
    S = 0
    for x in range(i):
        Cx = C[x]
        for h in range(3):
            y0 = (h + x - 1) % 3                 # h = 1 + y - x (mod 3)
            if x == 0 and y0 == 0:
                y0 = 3
            if y0 >= j:
                continue
            n = (j - 1 - y0) // 3 + 1
            a_ = i - x - 1 + h
            c0 = j - y0 + 1 - h
            cl = c0 - 3 * (n - 1)
            S += sum(map(mul, Cx[y0:j:3], reversed(AW[h][a_][cl:c0 + 1:3])))
    return S


def _worker(pairs):
    A, C, AW, C00 = _G['A'], _G['C'], _G['AW'], _G['C00']
    bad = []
    for i, j in pairs:
        S = _S(i, j, C, AW)
        if (-2 * S + C00 * i * j) // (2 * C00 * i * j) != A[i][j]:
            bad.append((i, j))
    return len(pairs), bad


def generate_chart(N, b):
    """the recursion of certificate.tex:111-149, from nothing"""
    Qv = 1 << b
    A = [[0] * (N - i + 1) for i in range(N + 1)]
    C = [[0] * (N - i + 1) for i in range(N + 1)]
    AW = [[[0] * (N - i + 1) for i in range(N + 1)] for _ in range(3)]

    def setc(a_, c_):
        v = A[a_][c_]
        C[a_][c_] = 72 * v + Qv * CC.get((a_, c_), 0)
        AW[0][a_][c_] = v * c_ * (c_ - 1)
        AW[1][a_][c_] = v * a_ * c_
        AW[2][a_][c_] = v * a_ * (a_ - 1)
    for k in range(N + 1):
        zk = ZK[k] if k < 8 else 0
        v = (2 * Qv * zk + 100000) // 200000          # rnd(Q Z_k / 100000)
        A[0][k] = v
        A[k][0] = v
        setc(0, k)
        setc(k, 0)
    C00 = C[0][0]
    for d in range(2, N + 1):
        for i in range(1, d // 2 + 1):
            j = d - i
            S = _S(i, j, C, AW)
            v = (-2 * S + C00 * i * j) // (2 * C00 * i * j)
            A[i][j] = v
            A[j][i] = v
            setc(i, j)
            setc(j, i)
    return A


def unflatten(vals, N):
    """the files list degree by degree, A_{d,0}, A_{d-1,1}, ..., A_{0,d}"""
    A = [[None] * (N - i + 1) for i in range(N + 1)]
    k = 0
    for d in range(N + 1):
        for i in range(d, -1, -1):
            A[i][d - i] = vals[k]
            k += 1
    return A


def verify_chart(vals, N, b, workers):
    """the supplied chart is the fixed point of the recursion: pure coefficients, symmetry, and every A_ij recomputed
    from the file's own lower-degree entries. By induction on degree the file then equals the recursion's output."""
    Qv = 1 << b
    if len(vals) != (N + 1) * (N + 2) // 2:
        return False, 'wrong length %d' % len(vals), None
    A = unflatten(vals, N)
    pure = all(A[0][k] == A[k][0] == (2 * Qv * (ZK[k] if k < 8 else 0) + 100000) // 200000 for k in range(N + 1))
    sym = all(A[i][j] == A[j][i] for i in range(N + 1) for j in range(N + 1 - i))
    C, AW = _tables(A, N, Qv)
    pairs = [(i, d - i) for d in range(2, N + 1) for i in range(1, d // 2 + 1)]
    pairs.sort(key=lambda p: -p[0] * p[1])
    nb = max(1, workers)
    bins = [[] for _ in range(nb)]
    load = [0] * nb
    for p in pairs:
        k = load.index(min(load))
        bins[k].append(p)
        load[k] += p[0] * p[1] + 1
    _G.update(A=A, C=C, AW=AW, C00=C[0][0])
    if nb == 1:
        res = [_worker(bins[0])]
    else:
        ctx = multiprocessing.get_context('fork')
        with ctx.Pool(nb) as pool:
            res = pool.map(_worker, bins)
    checked = sum(r[0] for r in res)
    bad = [x for r in res for x in r[1]]
    _G.clear()
    ok = pure and sym and not bad and checked == len(pairs)
    return ok, 'pure %s, symmetric %s, %d recursion equations checked, %d fail %s' % (pure, sym, checked, len(bad), bad[:3]), A


def residual_bound(A, N, b):
    """rho + sum_s sum_{k+m>N} D_{s,k} V_{s,m} of eq. (cert:residual-sum), as an exact rational"""
    Qv = 1 << b
    Cs = [[0] * (N + 1) for _ in range(3)]
    Vs = [[0] * (N + 1) for _ in range(3)]
    for a_ in range(N + 1):
        for c_ in range(N + 1 - a_):
            k = a_ + c_
            Cv = 72 * A[a_][c_] + Qv * CC.get((a_, c_), 0)
            Cs[(a_ - c_) % 3][k] += abs(Cv)
            av = abs(A[a_][c_])
            Vs[0][k] += av * a_ * c_
            Vs[1][k] += av * c_ * (c_ - 1)
            Vs[2][k] += av * a_ * (a_ - 1)
    # sum_s sum_{k+m>N} (Cs R^k / Q)(Vs R^(m-2) / Q): with R^e = 31^e 25^(N-e) / 25^N, suffix sums over m
    num = 0
    for s_ in range(3):
        suf = [0] * (N + 2)
        for m in range(N, 1, -1):
            suf[m] = suf[m + 1] + Vs[s_][m] * 31 ** (m - 2) * 25 ** (N - m + 2)
        for k in range(N + 1):
            if Cs[s_][k]:
                num += Cs[s_][k] * 31 ** k * 25 ** (N - k) * suf[max(2, N - k + 1)]
    p25 = [1, 25 ** N]
    tail = Fraction(num, p25[1] * p25[1] * Qv * Qv)
    rho = sum(Fraction(36 * (k + 1) * k * k) * R ** (k - 2) for k in range(2, N + 1)) / Qv
    return rho + tail, rho, tail


def weighted_sum(coef, N, scale_bits, weight, lo=0, hi=None):
    """sum_{lo <= i+j <= hi} |coef(i,j)| / 2^scale_bits * R^(i+j) * weight(i+j), exactly (R = 31/25)"""
    hi = N if hi is None else hi
    num = 0
    for k in range(lo, hi + 1):
        m = sum(abs(coef(i, k - i)) for i in range(k + 1))
        if m:
            num += m * weight(k) * 31 ** k * 25 ** (hi - k)
    return Fraction(num, 25 ** hi * (1 << scale_bits))


