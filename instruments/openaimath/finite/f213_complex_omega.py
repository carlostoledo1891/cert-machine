    check(checks, 'S5 shell: r_* = .35670524, r_1 = .33437745, r_2 = 2.13289155, rho >= .20947544 > .2, |z\'| <= .69108269, |z\'\'| <= 3.15835169 < 3.16, |(H_W o z)\'\'| < 30.348',
          rs == Fraction('.35670524') and r1 == Fraction('.33437745') and r2 == Fraction('2.13289155') and rmin == Fraction('.20947544')
          and zp == Fraction('.69108269') and zpp == Fraction('3.15835169') and S[2] * zp ** 2 + S[1] * zpp < Fraction('30.348'),
          '%.4f' % float(S[2] * zp ** 2 + S[1] * zpp))
    B = Fraction(2 ** 52)
    e = [Fraction(15 * r) / B for r in range(13)]
    f = Fraction(400) / B
    for r in range(1, 13):
        f = f / 2 + 2 * e[r] + Fraction(250) / B
    eh, fh = Fraction(180) / B, Fraction(1700) / B
    for _ in range(14):
        eh = 2 * eh + Fraction(42) / B
        fh = Fraction(2, 3) * fh + 3 * eh + Fraction(250) / B
    check(checks, 'S6 library error recurrences: f_12^init <= 1159.991/B, e_14 = 3637206/B < 8.5e-10, f_14 < 3.635e-9 < 1e-8 (certificate-w.tex:313-362)',
          f * B <= Fraction('1159.991') and e[12] * B == 180 and eh * B == 3637206 and eh < Fraction('8.5e-10') and fh < Fraction('3.635e-9'),
          'f12 %.3f/B, e14 %s/B, f14 %.4g' % (float(f * B), eh * B, float(fh)))
    return S


