def decide(src=None, full=True, charts=True, workers=None, rect_script=(-2, 2, 2, -3, 2, -2, 3), zero_fiber=None, claimed_alpha='0.465',
           const_override=None, chart420_override=None, s_override=None, hw_dmax=110, regen420=False):
    """full=False skips the 18 MB chart and what depends on it; charts=False also skips the 420 chart (forges only)"""
    t0 = time.time()
    src = src or Sources()
    checks = []
    timing = {}
    main = src.text(MAIN)
    intro = src.text(INTRO)
    cert = src.text(CERT)
    certw = src.text(CERTW)
    btex = src.text(BARRIER_TEX)
    repro = src.text(REPRO)
    rect = src.text(RECT)
    newc = src.text(NEWC22)
    check(checks, 'the headline as printed: omega < 1129/500 = 2.258, alpha > 0.465, w(0.709) < 2.092',
          '\\omega<\\frac{1129}{500}=2.258,\\qquad' in intro and '\\alpha>0.465,\\qquad w(0.709)<2.092' in intro and '\\(\\omega<2.258\\)' in main)
    other = src.text(OTHER + 'build/paper.tex')
    src.text(OTHER + 'README.md')
    check(checks, '#212 (omega <= 9/4) as read: Theorem thm:main states omega <= 9/4; its TeX has no verbatim / tabular / listing block',
          '$\\omega\\leq9/4$' in other and not re.search(r'\\begin\{(verbatim|tabular|lstlisting|longtable)\}', other))

    t = time.time()
    rect_checks(checks, rect, rect_script, zero_fiber, claimed_alpha)
    timing['rectangular'] = round(time.time() - t, 1)
    t = time.time()
    barrier_checks(checks, btex, newc, cert, repro, const_override)
    hw_checks(checks, certw, s_override, hw_dmax)
    timing['barrier_and_W'] = round(time.time() - t, 1)

    workers = workers or max(1, min(6, (os.cpu_count() or 2) - 2))
    value = {}
    if charts:
        t = time.time()
        v420 = [int(x) for x in src.text(QP420).split()]
        if chart420_override:
            for k, delta in chart420_override.items():
                v420[k] += delta
        ok420, det420, A420 = verify_chart(v420, 420, 224, workers)
        check(checks, 'S2 qP420_gmp is the fixed point of the chart recursion (certificate.tex:111-149) at N = 420, b = 224', ok420, det420)
        check(checks, 'S2 21 < C_00/Q < 22 at b = 224', 21 * 2 ** 224 < 72 * v420[0] + 8 * 2 ** 224 < 22 * 2 ** 224)
        timing['P420'] = round(time.time() - t, 1)
        if regen420:
            t = time.time()
            G420 = generate_chart(420, 224)
            check(checks, 'S2 (second derivation) P_{420,224} regenerated from nothing by the recursion equals qP420_gmp, all 88,831 entries',
                  [G420[i][d - i] for d in range(421) for i in range(d, -1, -1)] == v420)
            timing['P420_regenerated'] = round(time.time() - t, 1)
    if charts and full:
        t = time.time()
        v780 = [int(x) for x in src.text(QP780).split()]
        ok780, det780, A780 = verify_chart(v780, 780, 500, workers)
        timing['P780'] = round(time.time() - t, 1)
        check(checks, 'S2 qP780_gmp (18 MB) is the fixed point of the chart recursion at N = 780, b = 500 (so it IS the defined chart P)', ok780, det780)
        pnum = (2 * 2 ** 500 * 18623 + 100000) // 200000
        check(checks, 'S2 21 < C_00/Q < 22 at b = 500; Theorem thm:certificate\'s p = 2^-500 rnd(2^500 18623/100000) = A_00/2^500; E_1(0) = 1/3 - P(0) > .1471',
              21 * 2 ** 500 < 72 * v780[0] + 8 * 2 ** 500 < 22 * 2 ** 500 and v780[0] == pnum
              and Fraction(1, 3) - Fraction(v780[0], 2 ** 500) > Fraction('.1471'))
        t = time.time()
        if ok780:
            eps, rho, tail = residual_bound(A780, 780, 500)
            check(checks, 'S3 eps = sup |L P| <= rho + sum D V < 3.328667e-22 (certificate.tex:209-212), exact rational; 6 eps/eta < 9.987e-13 < 1e-12',
                  eps < Fraction('3.328667e-22') and 6 * Fraction('3.329e-22') / Fraction('2e-9') <= Fraction('9.987e-13')
                  and 6 * eps / Fraction('2e-9') < Fraction('9.987e-13'), 'eps <= %.10g (rho %.4g, products %.4g)' % (float(eps), float(rho), float(tail)))
            value['eps_upper'] = '%.10g' % float(eps)
            chart_checks(checks, A780, A420)
        else:
            check(checks, 'S3 the residual eps (needs the verified chart)', False, 'the chart failed its recursion')
        timing['residual_and_table'] = round(time.time() - t, 1)
    allpass = all(c['pass'] for c in checks)
    verdict = 'REFUSED' if allpass else 'REFUTED'
    value.update(timing=timing, seconds=round(time.time() - t0, 1), workers=workers, full=full, charts=charts,
                 decided=sum(1 for c in checks), refused_because=REFUSED_BECAUSE)
    return {'verdict': verdict, 'checks': checks, 'sources': src.read, 'value': value,
            'decides': 'finite components only: the three rectangular witnesses (alpha > 0.465, w(0.709) < 2.092, family '
                       'omega < 2.267) as finite computations; for omega < 2.258 the barrier, both charts (the 18 MB chart '
                       'verified as the recursion\'s output), the residual eps, the chart comparisons and the W-seed '
                       'polynomial. NOT the interior lemma (cost), NOT the boundary lemma / W-seed library (records not '
                       'published), hence NOT Theorem thm:certificate; no theory'}


