# ---------------------------------------------------------------- fixed-point intervals (integers / 2^P)
P = 256
G = 32
Q_ = P + G


def iratio(n, d):
    if d < 0:
        n, d = -n, -d
    return ((n << P) // d, -((-n << P) // d))


def ifrac(fr):
    fr = Fraction(fr)
    return iratio(fr.numerator, fr.denominator)


def iadd(a, b):
    return (a[0] + b[0], a[1] + b[1])


def isub(a, b):
    return (a[0] - b[1], a[1] - b[0])


def iscale(a, k):
    return (a[0] * k, a[1] * k) if k >= 0 else (a[1] * k, a[0] * k)


def imul(a, b):
    ps = (a[0] * b[0], a[0] * b[1], a[1] * b[0], a[1] * b[1])
    return (min(ps) >> P, -((-max(ps)) >> P))


def idiv(a, b):
    if b[0] <= 0:
        raise ValueError('division by an interval that is not positive')
    return (min((x << P) // y for x in a for y in b), max(-((-x << P) // y) for x in a for y in b))


def ipow(a, m):
    r = (1 << P, 1 << P)
    for _ in range(m):
        r = imul(r, a)
    return r


def _atanh(num, den, terms, upper, tail_factor):
    if upper:
        z = -((-num << Q_) // den)
        z2 = -((-(z * z)) >> Q_)
    else:
        z = (num << Q_) // den
        z2 = (z * z) >> Q_
    pw, s = z, 0
    for j in range(terms):
        s += -((-pw) // (2 * j + 1)) if upper else pw // (2 * j + 1)
        pw = -((-(pw * z2)) >> Q_) if upper else (pw * z2) >> Q_
    return s + (tail_factor * pw if upper else 0)


_N3 = Q_ // 3 + 8
LN2Q = (2 * _atanh(1, 3, _N3, False, 0), 2 * _atanh(1, 3, _N3, True, 2))       # tail <= 9/8 z^(2n+1) < 2 z^(2n+1)
LNTAB = [(2 * _atanh(m, 64 + m, _N3, False, 0), 2 * _atanh(m, 64 + m, _N3, True, 2)) for m in range(32)]
_NT = Q_ // 12 + 3


def _ln_bound(v, upper):
    """bound of ln(v / 2^P) * 2^Q_; ln = e ln 2 + ln(1 + m/32) + 2 atanh(z), z < 1/64, tail <= z^(2n+1)"""
    k = v.bit_length() - 1
    m = ((v << 5) >> k) - 32
    e = k - P
    num = 32 * v - ((32 + m) << k)
    den = 32 * v + ((32 + m) << k)
    if upper:
        return 2 * _atanh(num, den, _NT, True, 1) + LNTAB[m][1] + (e * LN2Q[1] if e >= 0 else e * LN2Q[0])
    return 2 * _atanh(num, den, _NT, False, 0) + LNTAB[m][0] + (e * LN2Q[0] if e >= 0 else e * LN2Q[1])


def ilog(a):
    if a[0] <= 0:
        raise ValueError('log of a non-positive interval')
    return (_ln_bound(a[0], False) >> G, -((-_ln_bound(a[1], True)) >> G))


def iexp(a):
    """exp of an interval: halve until |x| <= 1/2, Taylor to 80 terms with remainder 2|x|^80/80!, square back"""
    lim = max(abs(a[0]), abs(a[1]))
    s = 0
    while lim > (1 << (P - 1)):
        lim >>= 1
        s += 1
    x = (a[0] >> s, -((-a[1]) >> s))           # outward
    one = (1 << P, 1 << P)
    t, tot = one, one
    for n in range(1, 80):
        t = idiv(imul(t, x), (n << P, n << P))
        tot = iadd(tot, t)
    xm = max(abs(x[0]), abs(x[1]))
    rem = -((-(2 * xm ** 80)) // (math.factorial(80) * (1 << (79 * P)))) + 1
    tot = (tot[0] - rem, tot[1] + rem)
    for _ in range(s):
        tot = imul(tot, tot)
    return tot


def iint(k):
    return (k << P, k << P)


LN2 = ilog(iint(2))
LN3 = ilog(iint(3))


def gtF(iv, fr):
    fr = Fraction(fr)
    return iv[0] * fr.denominator > fr.numerator << P


def ltF(iv, fr):
    fr = Fraction(fr)
    return iv[1] * fr.denominator < fr.numerator << P


def inside(iv, a, b):
    return gtF(iv, a) and ltF(iv, b)


def dec(iv, d=15):
    sc = 10 ** d
    lo, hi = (iv[0] * sc) >> P, -((-(iv[1] * sc)) >> P)

    def f(q):
        s = '-' if q < 0 else ''
        q = abs(q)
        return '%s%d.%0*d' % (s, q // sc, d, q % sc)
    return '[%s, %s]' % (f(lo), f(hi))


def near(iv, center, tol):
    c = Fraction(center)
    return inside(iv, c - Fraction(tol), c + Fraction(tol))


def tight_agree(a, b, eps=Fraction(1, 10 ** 60)):
    """two enclosures of what the paper says is one number agree to 1e-60 (a consistency check, not an identity proof)"""
    return inside(isub(a, b), -eps, eps)


