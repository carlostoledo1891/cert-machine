#!/usr/bin/env python3
"""Pack lp_search's certificate into Lean pieces with checkpoint stacks (cert-machine, 2026-11-21).

The kernel's caches grow ~0.9 MB per certificate node, so one `decide +kernel` over all 32,529 nodes does not fit
the Mac's 16 GB. The certificate is cut into pieces of PIECE nodes; piece j is checked as its own theorem
`runAll cert_j stk_j = some stk_{j+1}`, with the stacks written out as literals. This script computes those stacks
by mirroring the Lean checker (LemmaPCheck.lean) step for step; a mismatch cannot pass, because the kernel
recomputes every piece and compares with the literal.

Entry = side + 2 * sum(v_i * 64**i) over the 8 vertices of the requirement, ascending (49 bits).
Usage: gen_pieces.py cert.txt Out.lean
"""
import sys

PIECE = 2048
CHUNK = 256
FULL = 2**35 - 1
BASE = sum(2**d for d in (1, 7, 11, 16, 19, 24, 28, 34))


def adjM(v):
    return ((BASE << v) | (BASE >> max(35 - v, 0))) & FULL


def bit(m, v):
    return (m >> v) & 1 == 1


def side_sets(side):
    return (1, 2) if side else (0, 1)


def vlist(x, n):
    out = []
    for _ in range(n):
        out.append(x % 64)
        x //= 64
    return out


def mask_of(vs):
    m = 0
    for v in vs:
        m |= 1 << v
    return m


def valid(st, side, vs):
    s, _ = st
    m = mask_of(vs)
    X0, X1 = side_sets(side)
    return (len(set(vs)) == len(vs) and all(v < 35 for v in vs)
            and all(adjM(u) & m == 0 for u in vs) and (m & (s[X0] | s[X1])) == 0)


def kids(occ, st, opts):
    out = []
    s, f = st
    for v, X in opts:
        if not bit(occ, v) and not bit(f[X], v) and (adjM(v) & s[X]) == 0:
            s2 = list(s); s2[X] |= 1 << v
            out.append((tuple(s2), f))
            f2 = list(f); f2[X] |= 1 << v
            f = tuple(f2)
    return out


def step(stack, e):
    assert stack, "empty stack before the certificate ends"
    st, rest = stack[0], stack[1:]
    side = e % 2 == 1
    vs = vlist(e // 2, 8)
    assert valid(st, side, vs), f"invalid requirement {e}"
    X0, X1 = side_sets(side)
    opts = [(v, X) for v in vs for X in (X0, X1)]
    s, _ = st
    return kids(s[0] | s[1] | s[2], st, opts) + rest


def lit(st):
    s, f = st
    return f"⟨{s[0]}, {s[1]}, {s[2]}, {f[0]}, {f[1]}, {f[2]}⟩"


def main():
    src, out = sys.argv[1], sys.argv[2]
    entries = []
    with open(src) as fh:
        for line in fh:
            side, mask = line.split()
            m = int(mask, 16)
            vs = [v for v in range(35) if (m >> v) & 1]
            assert len(vs) == 8 and m >> 35 == 0
            e = int(side)
            for i, v in enumerate(vs):
                e |= v << (1 + 6 * i)
            entries.append(e)
    init = [((1, 0, 0), (0, 0, 0)), ((0, 0, 0), (FULL, 0, 0))]
    stacks = [init]
    pieces = []
    stack = init
    for j in range(0, len(entries), PIECE):
        part = entries[j:j + PIECE]
        for e in part:
            stack = step(stack, e)
        pieces.append(part)
        stacks.append(stack)
    assert stack == [], f"stack not empty at the end: {len(stack)}"
    with open(out, "w") as fh:
        fh.write(f"import LemmaPCheck\n\n/-! Generated by gen_pieces.py from {src.split('/')[-1]}: {len(entries)} nodes in "
                 f"{len(pieces)} pieces of up to {PIECE}, with the stack at each cut. Data only. -/\n\n"
                 "namespace RamseyScout.LemmaPCert\nopen RamseyScout.PathLemma.Check\n\n")
        for j, part in enumerate(pieces):
            chunks = [part[i:i + CHUNK] for i in range(0, len(part), CHUNK)]
            fh.write(f"def cert{j} : List (List Nat) := [\n" +
                     ",\n".join("  [" + ", ".join(str(e) for e in c) + "]" for c in chunks) + "]\n\n")
        for j, stk in enumerate(stacks):
            if j == 0:
                fh.write("def stk0 : List St := [initA, initE]\n")
            else:
                fh.write(f"def stk{j} : List St := [" + ", ".join(lit(s) for s in stk) + "]\n")
        fh.write("\nend RamseyScout.LemmaPCert\n")
    print(f"{len(entries)} entries, {len(pieces)} pieces, max stack {max(len(s) for s in stacks)} -> {out}")


if __name__ == "__main__":
    main()
