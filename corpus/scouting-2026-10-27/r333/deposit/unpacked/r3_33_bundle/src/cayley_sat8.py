"""Cayley-graph search for (3,k)-Ramsey graphs by CEGAR with an incremental SAT solver.
Blue graph Cay(G,S) (S = S^-1, e not in S) must be triangle-free; red = complement must have no K_k.
Variables: one per inverse-class {s, s^-1}. Triangle-freeness: for s1*s2 = s3 (all in S) forbidden -> clauses.
Counterexamples: a red k-clique C containing e (blue-independent k-set) -> clause OR_{x!=y in C} [x^-1 y in S].
Usage: cayley_sat.py <group> <k> <outdir> [time_limit_s]
group: Z<n> | Z<a>xZ<b>[xZ<c>] | M<m>_<n>_<r> (Z_m semidirect Z_n, b acts by a -> r*a) | D<m> (= M<m>_2_<m-1>)"""
import sys, os, re, time, json, subprocess, itertools
import numpy as np
from pysat.solvers import Solver

def _component(spec):
    """returns (elements as tuples, mul function, list of automorphism maps on elements)"""
    from math import gcd
    if spec.startswith('G'):   # generalized dihedral Dih(Z_a x Z_b) = (Z_a x Z_b) x| Z_2, inversion
        a_, b_ = map(int, spec[1:].split('_'))
        els = [(x, y, t) for t in range(2) for y in range(b_) for x in range(a_)]
        f = lambda g, h: ((g[0] + (1 - 2 * g[2]) * h[0]) % a_, (g[1] + (1 - 2 * g[2]) * h[1]) % b_, (g[2] + h[2]) % 2)
        auts = [(lambda u: (lambda g: ((u * g[0]) % a_, g[1], g[2])))(u) for u in range(2, a_) if gcd(u, a_) == 1]
        auts += [(lambda u: (lambda g: (g[0], (u * g[1]) % b_, g[2])))(u) for u in range(2, b_) if gcd(u, b_) == 1]
        if a_ == b_: auts.append(lambda g: (g[1], g[0], g[2]))
        return els, f, auts
    if spec.startswith('D'):
        m = int(spec[1:]); spec = f'M{m}_2_{m-1}'
    if spec.startswith('M'):
        m, n, r = map(int, spec[1:].split('_'))
        assert pow(r, n, m) == 1 % m, 'r^n must be 1 mod m'
        els = [(a, b) for b in range(n) for a in range(m)]
        rp = [pow(r, b, m) for b in range(n)]
        f = lambda g, h: ((g[0] + rp[g[1]] * h[0]) % m, (g[1] + h[1]) % n)
        auts = [(lambda u: (lambda g: ((u * g[0]) % m, g[1])))(u) for u in range(2, m) if gcd(u, m) == 1]
        return els, f, auts
    q = int(spec[1:])
    els = [(a,) for a in range(q)]
    f = lambda g, h: ((g[0] + h[0]) % q,)
    auts = [(lambda u: (lambda g: ((u * g[0]) % q,)))(u) for u in range(2, q) if gcd(u, q) == 1]
    return els, f, auts

def make_group(spec):
    """spec: factors joined by 'x', each Z<n> | D<m> | M<m>_<n>_<r>; group = direct product"""
    comps = [_component(c) for c in spec.split('x')]
    els = list(itertools.product(*[c[0] for c in comps]))
    idx = {g: i for i, g in enumerate(els)}
    mul = np.array([[idx[tuple(c[1](x, y) for c, x, y in zip(comps, g, h))] for h in els] for g in els], dtype=np.int32)
    gens = []
    for ci, c in enumerate(comps):
        for au in c[2]:
            gens.append(np.array([idx[tuple(au(x) if j == ci else x for j, x in enumerate(g))] for g in els], dtype=np.int64))
    return mul, gens

def closure(mul, gens, cap=1500):
    """Group generated by the given automorphisms plus all inner automorphisms (capped)."""
    n = len(mul)
    e = int(np.where((mul == np.arange(n)[None, :]).all(axis=1))[0][0])
    inv = np.array([int(np.where(mul[g] == e)[0][0]) for g in range(n)])
    gens = list(gens) + [mul[mul[g], :][:, inv[g]] if False else np.array([mul[mul[g, x], inv[g]] for x in range(n)], dtype=np.int64) for g in range(n)]
    ident = tuple(range(n)); seen = {ident}; frontier = [np.arange(n)]; out = []
    gens = [gp for gp in gens if tuple(gp) != ident]
    uniq = {}
    for gp in gens: uniq[tuple(gp)] = gp
    gens = list(uniq.values())
    while frontier and len(seen) < cap:
        nxt = []
        for f in frontier:
            for gp in gens:
                h = gp[f]; t = tuple(h)
                if t not in seen:
                    seen.add(t); out.append(h); nxt.append(h)
                    if len(seen) >= cap: break
            if len(seen) >= cap: break
        frontier = nxt
    return out

def main():
    spec, k, outdir = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    tlim = float(sys.argv[4]) if len(sys.argv) > 4 else 36000
    os.makedirs(outdir, exist_ok=True)
    CLQ = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'bin', 'clq3')
    mul, auts = make_group(spec); n = len(mul)
    auts = closure(mul, auts)
    e = int(np.where((mul == np.arange(n)[None, :]).all(axis=1))[0][0])
    inv = np.array([int(np.where(mul[g] == e)[0][0]) for g in range(n)])
    # inverse classes -> SAT variables 1..V
    cls = -np.ones(n, dtype=int); V = 0
    for g in range(n):
        if g != e and cls[g] < 0:
            V += 1; cls[g] = V; cls[inv[g]] = V
    s = Solver(name='cadical153')
    seen = set()
    for a in range(n):
        if a == e: continue
        for b in range(n):
            if b == e: continue
            c = mul[a, b]
            if c == e: continue
            cl = tuple(sorted({int(cls[a]), int(cls[b]), int(cls[c])}))
            if cl not in seen:
                seen.add(cl); s.add_clause([-int(v) for v in cl])
    nlex = 0
    if os.environ.get('LEX', '1') == '1':
        top = V
        for a in auts:
            pc = np.zeros(V + 1, dtype=int)          # class permutation induced by automorphism a
            for g in range(n):
                if g != e: pc[cls[g]] = cls[a[g]]
            if all(pc[i] == i for i in range(1, V + 1)): continue
            prev = None                               # lex-leader: x <=_lex x o pc
            for i in range(1, V + 1):
                x, y = i, int(pc[i])
                if x == y: continue
                pre = [] if prev is None else [-prev]
                s.add_clause(pre + [-x, y])
                top += 1; ei = top
                s.add_clause(pre + [-x, -y, ei]); s.add_clause(pre + [x, y, ei])
                prev = ei
            nlex += 1
    tri = [[] for _ in range(V + 1)]
    for cl in seen:
        for v in cl: tri[v].append([w for w in cl if w != v])
    rng = np.random.default_rng(int(os.environ.get('SEED', '1')))
    def extend(inS):
        order = rng.permutation(np.arange(1, V + 1))
        for v in order:
            if inS[v]: continue
            if all(not all(inS[w] for w in rest) for rest in tri[v]):
                inS[v] = True
        return inS
    log = open(os.path.join(outdir, 'log.txt'), 'a')
    def say(*x):
        t = ' '.join(map(str, x)); print(t, flush=True); log.write(t + '\n'); log.flush()
    say(f'group {spec} order {n} auts {len(auts)} lex {nlex} vars {V} tri-clauses {len(seen)} k={k}')
    gfile = os.path.join(outdir, 'red.clq')
    # left-mult: x^-1 y
    t0 = time.time(); it = 0
    while time.time() - t0 < tlim:
        it += 1
        if not s.solve():
            say(f'UNSAT after {it} iters ({time.time()-t0:.0f}s): no Cayley (3,{k})-graph on {spec}'); return
        model = s.get_model()
        inS = np.zeros(V + 1, dtype=bool)
        for lit in model[:V]:
            if lit > 0: inS[lit] = True
        inS = extend(inS)
        Sarr = np.array([g for g in range(n) if g != e and inS[cls[g]]], dtype=np.int64)
        tgt = mul[:, Sarr]
        src = np.repeat(np.arange(n), len(Sarr))
        dst = tgt.ravel()
        keep = src < dst
        with open(gfile, 'w') as f:
            f.write(f'p edge {n} {int(keep.sum())}\n')
            f.write(''.join(f'e {u+1} {v+1}\n' for u, v in zip(src[keep].tolist(), dst[keep].tolist())))
        r = subprocess.run([CLQ, gfile, str(k), '-', str(e + 1), 'c', os.environ.get('MULTI', '12')], capture_output=True, text=True)
        out = r.stdout.split()
        if out[0] == 'NONE':
            S = [g for g in range(n) if g != e and inS[cls[g]]]
            say(f'FOUND iter {it} ({time.time()-t0:.0f}s): |S|={len(S)} {r.stderr.strip()}')
            json.dump({'group': spec, 'k': k, 'order': n, 'S': S, 'mul_spec': spec}, open(os.path.join(outdir, 'found.json'), 'w'))
            os.replace(gfile, os.path.join(outdir, f'found_blue_{spec}_k{k}.clq'))
            return
        added = set()
        for line in r.stdout.strip().split('\n'):
            C = [int(v) - 1 for v in line.split()[1:]]
            D = np.array(sorted({int(mul[inv[x], y]) for x in C for y in C if x != y}), dtype=np.int64)
            for a in [None] + auts:
                cl = tuple(sorted({int(c) for c in cls[D if a is None else a[D]]}))
                if cl not in added:
                    added.add(cl); s.add_clause(list(cl))
        if it % 200 == 0: say(f'it {it} t={time.time()-t0:.0f}s |S|~{int(inS.sum())}')
    say(f'TIMEOUT after {it} iters')

if __name__ == '__main__':
    main()
