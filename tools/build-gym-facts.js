#!/usr/bin/env node
/* build-gym-facts.js — emit the gym's fact corpus as exact-rational Python.
   tools/ · cert-machine

   The environment ships as a stdlib-only Python wheel and must not depend on
   this engine at runtime, so the corpus is GENERATED from the records here and
   frozen into the package. Two properties survive the crossing:

     · every fact still names the record it came from and that record's sha256,
       so a reader can walk from a task back to the certificate;
     · endpoints become EXACT RATIONALS (numerator, denominator), not decimals.
       The whole environment is an argument about what decimals lose, so the
       corpus may not be stored as decimals.

   Doubles are exactly representable as rationals — every float is p/2^k — so
   this conversion is lossless in the direction that matters: the Python side
   holds precisely the interval the certificate proved, with no rounding of our
   own introduced on the way in.

   usage: node tools/build-gym-facts.js */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const L = require(path.join(ROOT, 'instruments/envs/lib.js'));

const die = (m) => { console.error('GYM FACTS REFUSED: ' + m); process.exit(1); };

/* a double as an exact fraction: mantissa/2^k, found by scaling until integral */
function exactFraction(x) {
  if (!Number.isFinite(x)) die('non-finite endpoint');
  if (Number.isInteger(x)) return [BigInt(x), 1n];
  let num = x, den = 1n;
  /* doubles have at most 1074 binary places; doubling until integral is exact */
  for (let i = 0; i < 1100 && !Number.isInteger(num); i++) { num *= 2; den *= 2n; }
  if (!Number.isInteger(num)) die('could not represent ' + x + ' exactly');
  return [BigInt(num), den];
}

const rows = [];
for (const f of L.FACTS) {
  if (!f.certified) continue;
  const [ln, ld] = exactFraction(f.lo), [hn, hd] = exactFraction(f.hi);
  rows.push({
    id: f.id, what: f.what, tier: f.tier,
    lo: [ln, ld], hi: [hn, hd],
    record: f.record || null, sha256: f.sha256 || null,
    publishedWrong: f.publishedWrong !== undefined ? f.publishedWrong : null
  });
}
if (rows.length < 50) die('the corpus is too small to ship — expected the ledger tier');

const q = (s) => JSON.stringify(String(s));
const py = [];
py.push('"""The certified fact corpus, generated — do not edit by hand.');
py.push('');
py.push('Every entry is a quantity this lab has enclosed in exact arithmetic, with the');
py.push('record it came from and that record\'s sha256 beside it. Endpoints are exact');
py.push('rationals (numerator, denominator): a certificate is a proof about an interval,');
py.push('and storing it as a decimal would throw away the thing this environment exists');
py.push('to talk about.');
py.push('');
py.push('Generated by tools/build-gym-facts.js from the cert-machine records.');
py.push('"""');
py.push('from fractions import Fraction');
py.push('from typing import NamedTuple, Optional');
py.push('');
py.push('');
py.push('class Fact(NamedTuple):');
py.push('    id: str');
py.push('    what: str');
py.push('    tier: str');
py.push('    lo: Fraction');
py.push('    hi: Fraction');
py.push('    record: Optional[str]');
py.push('    sha256: Optional[str]');
py.push('    published_wrong: Optional[float]');
py.push('');
py.push('    @property');
py.push('    def width(self) -> Fraction:');
py.push('        return self.hi - self.lo');
py.push('');
py.push('    @property');
py.push('    def midpoint(self) -> Fraction:');
py.push('        return (self.lo + self.hi) / 2');
py.push('');
py.push('');
py.push('FACTS = [');
for (const r of rows) {
  py.push('    Fact(');
  py.push('        id=' + q(r.id) + ',');
  py.push('        what=' + q(r.what) + ',');
  py.push('        tier=' + q(r.tier) + ',');
  py.push('        lo=Fraction(' + r.lo[0] + ', ' + r.lo[1] + '),');
  py.push('        hi=Fraction(' + r.hi[0] + ', ' + r.hi[1] + '),');
  py.push('        record=' + (r.record ? q(r.record) : 'None') + ',');
  py.push('        sha256=' + (r.sha256 ? q(r.sha256) : 'None') + ',');
  py.push('        published_wrong=' + (r.publishedWrong === null ? 'None' : String(r.publishedWrong)) + ',');
  py.push('    ),');
}
py.push(']');
py.push('');
py.push('BY_ID = {f.id: f for f in FACTS}');
py.push('NAMED = [f for f in FACTS if f.tier == "named"]');
py.push('NONDEGENERATE = [f for f in FACTS if f.width > 0]');
py.push('EXACT_INTEGER = [f for f in FACTS if f.width == 0]');
py.push('');

const out = path.join(ROOT, 'environments/break_the_grader/break_the_grader/facts.py');
fs.writeFileSync(out, py.join('\n'));
console.log('facts.py written: ' + rows.length + ' facts ('
  + rows.filter(r => r.tier === 'named').length + ' named, '
  + rows.filter(r => r.lo[0] * r.hi[1] === r.hi[0] * r.lo[1]).length + ' exact integers)');
