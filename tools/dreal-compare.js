const gitHead = () => { try { return cp.execFileSync('git', ['-C', ROOT, 'rev-parse', '--short=8', 'HEAD'], { encoding: 'utf8' }).trim(); } catch (e) { return null; } };
function runFiles(dir) {
  const d = abs(dir);
  need(fs.existsSync(d), 'no run directory ' + dir);
  const files = {};
  for (const f of fs.readdirSync(d).sort()) files[f] = shaBuf(fs.readFileSync(path.join(d, f)));
  need(files['dreal.json'] && files['ours-runner.json'] && files['run.json'], dir + ' must hold dreal.json, ours-runner.json and run.json');
  return files;
}
function liveGate() {
  const S = J(SCEN), G = J(LEDGER);
  for (const c of S.cases) {
    const live = F.decide(c.proposal, S.box, S.rules), rec = G.receipts.find((r) => r.id === c.id).receipt;
    need(live.verdict === rec.verdict && JSON.stringify(live.checks.map((k) => [k.id, k.verdict])) === JSON.stringify(rec.checks.map((k) => [k.id, k.verdict])), 'the gate decides ' + c.id + ' differently from its ledger');
  }
}
function assemble(dir, oursLocal, generated) {
  const C = J(CLAIMS), run = J(dir + '/dreal.json'), runner = J(dir + '/ours-runner.json'), meta = J(dir + '/run.json');
  need(buildClaims().equals(fs.readFileSync(abs(CLAIMS))), CLAIMS + ' differs from what its sources regenerate (run --claims, then a new run)');
  need(run.dreal.wheelSha256 === WHEEL.sha256, 'the run used a wheel with another sha256: ' + run.dreal.wheelSha256);
  need(run.dreal.package === '4.21.6.2', 'the run used dreal ' + run.dreal.package);
  for (const [k, v] of Object.entries(oursLocal.limiteWords)) need(GATE_WORD[v] === oursWord(C.claims.find((x) => x.id === k)), 'the timed procedure for ' + k + ' gives ' + v);
  const D = derive(C, run);
  for (const c of D.claims) if (c.family === 'flowline') { c.oursMs = { local: oursLocal.claims[c.id], runner: runner.claims[c.id] }; }
  else c.oursMs = { record: C.claims.find((x) => x.id === c.id).oursMs };
  for (const r of D.receipts) r.oursMs = { local: oursLocal.receipts[r.id], runner: runner.receipts[r.id] };
  return {
    what: 'cert-machine and dReal 4 (delta-complete; Gao, Avigad, Clarke) on the same claims: the Contraprova flow-line gate\'s nine receipts (every check as a claim, the printed enclosures, the bracket of Colebrook\'s root) and the self-audit\'s entropy family (4 originals, 12 mutants), each put to dReal at two deltas. dReal\'s unsat is a proof; delta-sat is not a witness — each delta-sat box of a flow-line query has its midpoint re-decided by the gate. Agreement means dReal\'s unsat matches our CERTIFIED/REFUTED and a split refusal of ours shows delta-sat on both sides; disagreements are reported as they fell. Written by tools/dreal-compare.js --record; --check re-derives every word, agreement and total from the stored run and refuses on drift.',
    name: 'dreal-compare',
    generated,
    git: gitHead(),
    run: { id: meta.databaseId, url: meta.url, headSha: meta.headSha, event: meta.event, conclusion: meta.conclusion, createdAt: meta.createdAt, dir, files: runFiles(dir) },
    dreal: { ...run.dreal, wheel: WHEEL, host: run.host, systemLibraries: fs.existsSync(abs(dir + '/ibex-version.txt')) ? fs.readFileSync(abs(dir + '/ibex-version.txt'), 'utf8').trim().split('\n') : null, started: run.started, finished: run.finished },
    deltas: C.deltas, timeoutSeconds: C.timeoutSeconds,
    claimsFile: { path: CLAIMS, sha256: sha(CLAIMS) },
    sources: C.sources,
    ours: { local: { machine: oursLocal.machine, unit: oursLocal.unit }, runner: { machine: runner.machine, unit: runner.unit }, entropy: 'decided.ms of ' + MUT + ' (the self-audit\'s own timing, this Mac, 2026-10-21)' },
    totals: D.totals,
    findings: D.findings,
    receipts: D.receipts,
    claims: D.claims
  };
}
