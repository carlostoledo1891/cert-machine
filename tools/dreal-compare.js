const BOX6 = ['L', 'D', 'eps', 'rho', 'mu', 'dz'];
const FBOX = ['1/100', '1/49'];                                   /* f = 1/s², s ∈ [7, 10]: see the header */
const DEFS = {
  v: '4*Q/(86400*pi*D**2)',                                       /* Q/A, A = πD²/4, Q in m³/d */
  Re: 'rho*v*D/mu',
  a: 'eps/(c37*D)',
  b: 'c251/Re',
  P: 'Pd + (rho*g*dz - f*(L/D)*rho*v**2/2)/100000',               /* bar: P_d + ρgΔz − f (L/D) ρv²/2 */
  ceiling: 'Pd + rho*g*dz/100000',                                /* friction ≥ 0 */
  h7: '7 + 2*log(a + b*7)/ln10',
  h10: '10 + 2*log(a + b*10)/ln10',
  colebrookAt: '1/sqrt(fc) + 2*log(a + b/sqrt(fc))/ln10'
};
const COLEBROOK = '1/sqrt(f) + 2*log(a + b/sqrt(f))/ln10 == 0';  /* 1/√f = −2 log10(ε/(3.7D) + 2.51/(Re √f)) */
const KCONST = () => ({ pi: PI, ln10: LN10, g: '9.80665', c37: '3.7', c251: '2.51' });

/* the bracket of Colebrook's root over the box, proved in the interval kernel: h(7; a₊, b₊) < 0 < h(10; a₋, b₋) */
function bracketProof(box, Q) {
  const B = F.box(box), K = F.kinematics(B, F.dec(Q));
  const a = I.div(B.eps, I.mul(F.dec('3.7'), B.D)), b = I.div(F.dec('2.51'), K.Re);
  const C2 = I.div(I.iv(2), T.log(I.iv(10)));
  const h = (s, aa, bb) => I.add(I.iv(s), I.mul(C2, T.log(I.add(I.iv(aa), I.mul(I.iv(bb), I.iv(s))))));
  const at7 = h(7, a[1], b[1])[1], at10 = h(10, a[0], b[0])[0];
  return { at7Upper: at7, at10Lower: at10, holds: at7 < 0 && at10 > 0 };
}

function flowline() {
  const S = J(SCEN), G = J(LEDGER);
  need(G.scenariosSha256 === sha(SCEN), 'the gate ledger was written for another scenarios.json');
  need(G.modules[GATE] === sha(GATE), 'the gate ledger was written by another flowline.js');
  const claims = new Map(), receipts = [];
  const vars = Object.fromEntries(BOX6.map((k) => [k, S.box[k]]).concat([['f', FBOX]]));
  const put = (id, kind, statement, params, given, queries, ours) => {
    if (!claims.has(id)) claims.set(id, { ...minimal({ id, family: 'flowline', kind, statement, vars, params: { ...KCONST(), ...params }, defs: DEFS, given, queries }), ours });
    return id;
  };
  const supports = new Set();
  for (const c of S.cases) {
    const rec = G.receipts.find((r) => r.id === c.id);
    need(rec && rec.receipt, 'no ledger receipt for ' + c.id);
    const p = c.proposal, R = rec.receipt, checks = [];
    const tag = 'Q' + p.Q + '-Pd' + p.Pd;
    const human = 'Q = ' + p.Q + ' m³/d, P_d = ' + p.Pd + ' bar';
    for (const k of R.checks) {
      let id = null;
      if (k.verdict === F.NAO) { checks.push({ check: k.id, gate: k.verdict, claim: null }); continue; }
      if (k.id === 'massa') id = put('flowline/massa/H' + p.split.header + '-W' + p.split.wells.join('+'), 'consistency',
        'the manifold conserves mass: header ' + p.split.header + ' m³/d = the sum of the wells (' + p.split.wells.join(' + ') + ')',
        Object.fromEntries([['H', p.split.header]].concat(p.split.wells.map((w, i) => ['W' + (i + 1), w]))), [],
        { phi: ['H == sum(' + p.split.wells.map((w, i) => 'W' + (i + 1)).join(', ') + ')'] }, k.verdict);
      else if (k.id === 'cinematica') id = put('flowline/cinematica/Q' + p.Q + '-v' + p.claim.v, 'consistency',
        'the claimed velocity ' + p.claim.v + ' m/s is Q/A for some declared diameter (Q = ' + p.Q + ' m³/d)', { Q: p.Q, vc: p.claim.v }, [], { phi: ['v == vc'] }, k.verdict);
      else if (k.id === 'energia') id = put('flowline/energia/Pd' + p.Pd + '-claim' + p.claim.Pwh, 'consistency',
        'the claimed P_wh = ' + p.claim.Pwh + ' bar needs no negative friction at some declared input: P_wh ≤ P_d + ρgΔz (P_d = ' + p.Pd + ' bar)',
        { Pd: p.Pd, claim: p.claim.Pwh }, [], { phi: ['claim <= ceiling'] }, k.verdict);
      else if (k.id === 'dominio') id = put('flowline/dominio/Q' + p.Q, 'precondition',
        'the flow is turbulent on the whole declared box, Re ≥ 4000, so Colebrook applies (Q = ' + p.Q + ' m³/d)', { Q: p.Q, Remin: '4000' }, [],
        { notphi: ['Re < Remin'], phi: ['Re >= Remin'] }, k.verdict);
      else if (k.id === 'velocidade') id = put('flowline/velocidade/Q' + p.Q + '-max' + S.rules.vMax, 'rule',
        'v(x†) ≤ ' + S.rules.vMax + ' m/s at the true input x† of the declared box (Q = ' + p.Q + ' m³/d)', { Q: p.Q, vMax: S.rules.vMax }, [],
        { notphi: ['v > vMax'], phi: ['v <= vMax'] }, k.verdict);
      else if (k.id === 'colebrook') {
        id = put('flowline/colebrook/Q' + p.Q + '-f' + p.claim.f, 'consistency',
          'the claimed friction factor f = ' + p.claim.f + ' solves Colebrook for some declared input (Q = ' + p.Q + ' m³/d)', { Q: p.Q, fc: p.claim.f }, [],
          { phi: ['colebrookAt == 0'] }, k.verdict);
      } else if (k.id === 'modelo') {
        id = put('flowline/modelo/' + tag + '-claim' + p.claim.Pwh, 'consistency',
          'the claimed P_wh = ' + p.claim.Pwh + ' bar is the model\'s value at some declared input (' + human + ')', { Q: p.Q, Pd: p.Pd, claim: p.claim.Pwh }, [COLEBROOK],
          { phi: ['P == claim'] }, k.verdict);
        const [lo, hi] = R.enclosure.map((x) => x.toFixed(1));
        put('flowline/enclosure/' + tag, 'universal', 'the printed enclosure: ' + lo + ' ≤ P_wh(x) ≤ ' + hi + ' bar for every declared input (' + human + ')',
          { Q: p.Q, Pd: p.Pd, lo, hi }, [COLEBROOK], { below: ['P < lo'], above: ['P > hi'] }, 'CERTIFIED');
      } else if (k.id === 'limite') {
        id = put('flowline/limite/' + tag + '-max' + S.rules.PwhMax, 'rule',
          'P_wh(x†) ≤ ' + S.rules.PwhMax + ' bar at the true input x† of the declared box (' + human + '), P_wh by Darcy–Weisbach with Colebrook\'s friction factor',
          { Q: p.Q, Pd: p.Pd, PwhMax: S.rules.PwhMax }, [COLEBROOK], { notphi: ['P > PwhMax'], phi: ['P <= PwhMax'] }, k.verdict);
      } else die('a check the comparison does not know: ' + k.id);
      if (id && claims.get(id).given.length && !supports.has(p.Q)) supports.add(p.Q);
      checks.push({ check: k.id, gate: k.verdict, claim: id });
    }
    receipts.push({ id: c.id, gate: R.verdict, checks });
  }
  for (const Q of [...supports].sort()) {
    const pr = bracketProof(S.box, Q);
    need(pr.holds, 'the Colebrook bracket is not proved for Q = ' + Q);
    put('flowline/bracket/Q' + Q, 'support', 'Colebrook\'s root lies in s = 1/√f ∈ (7, 10) for every declared input (Q = ' + Q + ' m³/d): h(7) < 0 < h(10)',
      { Q }, [], { low: ['h7 >= 0'], high: ['h10 <= 0'] }, 'HOLDS');
  }
  return { claims: [...claims.values()], receipts };
}

/* ---------------------------------------------------------------- (b) the entropy family -- */
/* p = n/d as an exact decimal enclosure with `sig` significant digits (one exact decimal when it terminates there) */
function decBracket(n, d, sig) {
  need(n > 0n && d > 0n, 'a probability must be positive');
  const at = (k) => (k >= 0 ? [n * 10n ** BigInt(k), d] : [n, d * 10n ** BigInt(-k)]);
  let k = sig - (n.toString().length - d.toString().length), q;
  for (;;) { const [a, b] = at(k); q = a / b; const L = q.toString().length; if (L > sig) k--; else if (L < sig) k++; else break; }
  const [a, b] = at(k), exact = q * b === a;
  const str = (m) => (k <= 0 ? (m * 10n ** BigInt(-k)).toString() : (() => { const s = m.toString().padStart(k + 1, '0'); return s.slice(0, s.length - k) + '.' + s.slice(s.length - k); })());
  return exact ? str(q) : [str(q), str(q + 1n)];
}
const big = (v) => BigInt(String(v));
const gcd = (a, b) => { while (b) [a, b] = [b, a % b]; return a < 0n ? -a : a; };
/* the law as the certificate prints it — NO door: a malformed law is read as written */
function lawOf(cert) {
  if (Array.isArray(cert.weights)) {
    const den = cert.weights.reduce((L, w) => L / gcd(L, big(w.den)) * big(w.den), 1n);
    return { den, pts: cert.weights.map((w) => [big(w.x), big(w.y), big(w.num) * (den / big(w.den))]) };
  }
  if (Array.isArray(cert.distribution_x_y_numden)) {
    const den = cert.distribution_x_y_numden.reduce((L, [, , nd]) => L / gcd(L, big(nd[1])) * big(nd[1]), 1n);
    return { den, pts: cert.distribution_x_y_numden.map(([x, y, nd]) => [big(x), big(y), big(nd[0]) * (den / big(nd[1]))]) };
  }
  const m = /^10\^(\d+)$/.exec(String(cert.denominator));
  need(Array.isArray(cert.distribution_x_y_num) && m, 'a certificate in no known encoding');
  return { den: 10n ** BigInt(m[1]), pts: cert.distribution_x_y_num.map(([x, y, n]) => [big(x), big(y), big(n)]) };
}
const FORMS = { X: [1n, 0n], Y: [0n, 1n], S: [1n, 1n], U: [1n, 2n], T: [1n, -1n] };
function sumdiffClaim(id, obj, meta) {
  const prob = String(obj.cert.problem).replace(/^C_?/i, '').toLowerCase();
  const den = prob === '3b' ? ['X', 'Y', 'S'] : ['X', 'Y', 'S', 'U'];
  const law = lawOf(obj.cert), params = { bar: obj.claim }, defs = {};
  for (const name of ['T', ...den]) {
    const [a, b] = FORMS[name], m = new Map();
    for (const [x, y, n] of law.pts) { const v = (x * a + y * b).toString(); m.set(v, (m.get(v) || 0n) + n); }
    const atoms = [...m.entries()].sort((u, w) => (BigInt(u[0]) < BigInt(w[0]) ? -1 : 1));
    atoms.forEach(([, n], j) => { params['p_' + name + '_' + j] = decBracket(n, law.den, 25); });
    defs['H_' + name] = 'sum(' + atoms.map((_, j) => '-p_' + name + '_' + j + '*log(p_' + name + '_' + j + ')').join(', ') + ')';
  }
  defs.rho = 'H_T/' + den.slice(0, -1).reduceRight((acc, nm) => 'Max(H_' + nm + ', ' + acc + ')', 'H_' + den[den.length - 1]);
  return minimal({ id, family: 'entropy', kind: 'rule', ...meta,
    statement: 'ρ(μ) = H(X−Y)/max(' + den.map((n) => ({ X: 'H(X)', Y: 'H(Y)', S: 'H(X+Y)', U: 'H(X+2Y)' }[n])).join(', ') + ') ≥ ' + obj.claim + ' for the ' + law.pts.length + '-point law of the certificate (C' + prob + '), entropies in nats',
    vars: {}, params, defs, given: [], queries: { notphi: ['rho < bar'], phi: ['rho >= bar'] } });
}
function feiClaim(id, obj, meta) {
  const art = obj.art, n = Number(art.n), N = 1 << n, hex = String(art.true_hex);
  const bitAt = (x) => { const i = hex.length - 1 - (x >> 2); return i < 0 ? 0 : (parseInt(hex[i], 16) >> (x & 3)) & 1; };
  /* a bit at or beyond 2^n: not a table of n inputs — no formula exists to give dReal */
  for (let x = N; x < hex.length * 4; x++) if (bitAt(x)) return { id, family: 'entropy', kind: 'rule', ...meta, encodable: false, why: 'the truth table sets a bit at or beyond 2^n = ' + N + ': the object is not a function of n = ' + n + ' inputs, so there is no ratio to state' };
  const a = new Float64Array(N);
  for (let x = 0; x < N; x++) a[x] = bitAt(x) ? -1 : 1;
  for (let h = 1; h < N; h <<= 1) for (let i = 0; i < N; i += h << 1) for (let j = i; j < i + h; j++) { const u = a[j], v = a[j + h]; a[j] = u + v; a[j + h] = u - v; }
  let sq = 0n, inf = 0n; const counts = new Map();
  for (let S = 0; S < N; S++) { if (!a[S]) continue; const v = BigInt(Math.abs(a[S])); sq += v * v; let pc = 0, t = S; while (t) { pc += t & 1; t >>= 1; } inf += BigInt(pc) * v * v; counts.set(Number(v), (counts.get(Number(v)) || 0) + 1); }
  const N4 = 4n ** BigInt(n), g = gcd(inf, N4);
  need(a[0] === 0 && sq === N4, id + ': the table is not balanced or Parseval fails');
  need((inf / g) + '/' + (N4 / g) === String(art.I), id + ': I = ' + (inf / g) + '/' + (N4 / g) + ' from the table, the artifact states ' + art.I);
  const ks = [...counts.keys()].sort((u, w) => u - w), params = { bar: obj.claim, Infl: (inf / g) + '/' + (N4 / g), two: '2' };
  for (const k of ks) params['w_' + k] = (BigInt(k) * BigInt(k)) + '/' + N4;
  const defs = { H: '-sum(' + ks.map((k) => counts.get(k) + '*w_' + k + '*log(w_' + k + ')').join(', ') + ')/log(two)', r: 'H/(Infl - 1)' };
  return minimal({ id, family: 'entropy', kind: 'rule', ...meta,
    statement: 'H/(I−1) > ' + obj.claim + ' for the n = ' + n + ' truth table: H = Σ ŵ log2(1/ŵ) over its ' + [...counts.values()].reduce((s, c) => s + c, 0) + ' nonzero Fourier weights (' + ks.length + ' distinct), I = ' + params.Infl,
    vars: {}, params, defs, given: [], queries: { notphi: ['r <= bar'], phi: ['r > bar'] } });
}
function entropy() {
  const reg = J(REGISTER), M = J(MUT).families.entropy.rows, out = [];
  for (const row of E.rows(reg, J)) {
    const rec = M.find((x) => x.rowId === row.rowId);
    need(rec, 'no self-audit row ' + row.rowId);
    const items = [{ cls: 'original', truth: rec.verdict === 'CERTIFIED' ? 'TRUE' : rec.verdict, obj: E.claimOf(row.entry), r: rec.original }]
      .concat(E.mutants(row.entry).map((m) => ({ cls: m.class, truth: m.truth, obj: m.claim, r: rec.mutants.find((x) => x.class === m.class) })));
    for (const it of items) {
      need(it.r && shaBuf(Buffer.from(JSON.stringify(it.obj))) === it.r.sha256, row.rowId + '/' + it.cls + ': the regenerated object is not the one the self-audit pinned');
      const id = 'entropy/' + row.rowId + '/' + it.cls;
      const meta = { object: { row: row.rowId, class: it.cls, truth: it.truth, sha256: it.r.sha256, record: MUT }, ours: it.r.decided.verdict, oursMs: it.r.decided.ms };
      out.push(it.obj.kind === 'sumdiff' ? sumdiffClaim(id, it.obj, meta) : feiClaim(id, it.obj, meta));
    }
  }
  return out;
}

