/* ---------------------------------------------------------------- the gate's own procedures, timed -- */
function oursTimes() {
  const S = J(SCEN), C = JSON.parse(buildClaims().toString()), B = F.box(S.box);
  const G = F.dec('9.80665');
  const median = (fn, reps, runs) => { const xs = []; for (let r = 0; r < runs; r++) { const t = process.hrtime.bigint(); for (let i = 0; i < reps; i++) fn(); xs.push(Number(process.hrtime.bigint() - t) / 1e6 / reps); } xs.sort((u, w) => u - w); return xs[runs >> 1]; };
  for (const c of S.cases) F.decide(c.proposal, S.box, S.rules);                     /* warm */
  const receipts = {}, claims = {}, words = {};
  for (const c of S.cases) receipts[c.id] = median(() => F.decide(c.proposal, S.box, S.rules), 1, 9);
  for (const cl of C.claims.filter((x) => x.family === 'flowline')) {
    const p = cl.params, Qd = p.Q ? F.dec(p.Q) : null, Pd = p.Pd ? F.dec(p.Pd) : null;
    const check = cl.id.split('/')[1];
    let fn, reps = 1000;
    if (check === 'limite') {
      reps = 1;
      /* decide()'s own sequence for check 8: the 64 corners, then the whole box both ways at depth 12 */
      fn = () => { const bound = Number(p.PwhMax), W = F.corners(B, Qd, Pd, bound, S.box);
        if (!W.above) { const r = F.decideLE(B, Qd, Pd, bound, 12); if (r.bad === 0 && r.open === 0) return 'PROVADO'; }
        if (!W.below) { const r = F.decideLE(B, Qd, Pd, bound, 12); if (r.ok === 0 && r.open === 0) return 'REFUTADO'; }
        return 'RECUSADO'; };
      words[cl.id] = fn();
    } else if (check === 'enclosure' || check === 'modelo') { reps = 1; fn = () => F.envelope(B, Qd, Pd, 7); }
    else if (check === 'velocidade' || check === 'dominio' || check === 'cinematica') fn = () => F.kinematics(B, Qd);
    else if (check === 'energia') fn = () => I.add(Pd, I.div(I.mul(I.mul(I.iv(B.rho[1]), G), I.iv(B.dz[1])), I.iv(1e5)));
    else if (check === 'colebrook') fn = () => { const K = F.kinematics(B, Qd); return F.colebrookX(I.div(B.eps, I.mul(F.dec('3.7'), B.D)), I.div(F.dec('2.51'), K.Re)); };
    else if (check === 'massa') fn = () => { const ws = Object.keys(p).filter((k) => /^W\d+$/.test(k)).map((k) => F.ratOf(p[k])); return QR.cmp(F.ratOf(p.H), ws.reduce((s, w) => QR.add(s, w), QR.ZERO)); };
    else if (check === 'bracket') fn = () => bracketProof(S.box, p.Q);
    else die('no timing procedure for ' + cl.id);
    claims[cl.id] = median(fn, reps, 9);
  }
  return { machine: { platform: process.platform + '-' + process.arch, os: os.release(), cpu: (os.cpus()[0] || {}).model || null, cpus: os.cpus().length, node: process.version },
    unit: 'milliseconds, median of 9 runs (a tiny check repeated 1000 times per run)', receipts, claims, limiteWords: words };
}

/* ---------------------------------------------------------------- answers → words → agreement -- */
const GATE_WORD = { PROVADO: 'CERTIFIED', REFUTADO: 'REFUTED', RECUSADO: 'REFUSED' };
function oursWord(cl) {
  if (cl.family === 'entropy') return cl.ours;
  if (cl.kind === 'consistency') return cl.ours === 'REFUTADO' ? 'REFUTED' : cl.ours === 'PROVADO' ? 'CONSISTENT' : die('a consistency check with word ' + cl.ours);
  if (cl.kind === 'universal' || cl.kind === 'support') return cl.ours;
  return GATE_WORD[cl.ours] || die('a gate word the comparison does not know: ' + cl.ours);
}
function drealWord(cl, ans) {
  const st = (q) => (ans[q] ? ans[q].answer : 'missing');
  const qs = Object.keys(cl.queries), sts = qs.map(st);
  if (sts.includes('error') || sts.includes('missing')) return 'ERROR';
  if (cl.kind === 'rule' || cl.kind === 'precondition') {
    if (st('notphi') === 'unsat' && st('phi') === 'unsat') return 'EMPTY';
    if (st('notphi') === 'unsat') return 'CERTIFIED';
    if (st('phi') === 'unsat') return 'REFUTED';
    return sts.includes('timeout') ? 'REFUSED (timeout)' : 'REFUSED';
  }
  if (cl.kind === 'consistency') return st('phi') === 'unsat' ? 'REFUTED' : st('phi') === 'timeout' ? 'REFUSED (timeout)' : 'CONSISTENT';
  if (cl.kind === 'universal') return sts.every((s) => s === 'unsat') ? 'CERTIFIED' : sts.includes('timeout') ? 'REFUSED (timeout)' : 'REFUSED';
  if (cl.kind === 'support') return sts.every((s) => s === 'unsat') ? 'HOLDS' : 'NOT SHOWN';
  return die('a claim kind the comparison does not know: ' + cl.kind);
}
const PROVED = new Set(['CERTIFIED', 'REFUTED', 'HOLDS']);
function agreement(cl, ours, dr) {
  if (cl.family === 'entropy' && cl.object.truth === 'MALFORMED') return 'door';
  if (dr === 'ERROR' || dr === 'EMPTY') return 'anomaly';
  if (ours === dr) return 'agree';
  /* the gate declines a receipt whenever the precondition is not certified; dReal may prove more (that it fails everywhere) */
  if (cl.kind === 'precondition' && ours === 'REFUSED' && dr !== 'CERTIFIED') return 'agree';
  if (PROVED.has(ours) && PROVED.has(dr)) return 'contradiction';
  if (cl.kind === 'consistency') return ours === 'REFUTED' ? 'dReal weaker' : 'dReal stronger';
  if (PROVED.has(ours)) return 'dReal weaker';
  if (PROVED.has(dr)) return 'dReal stronger';
  return 'differ';
}
/* a delta-sat box of a flow-line query, its midpoint re-decided by the gate's own arithmetic: is it a witness? */
function witness(cl, q, box) {
  if (cl.family !== 'flowline' || !box) return null;
  const atom = cl.queries[q][0], m = /^(\w+) (<=|<|>=|>|==) (\w+)$/.exec(atom);
  if (!m) return null;
  const S = J(SCEN), mid = {};
  for (const k of BOX6) mid[k] = box[k] ? (Number(box[k][0]) + Number(box[k][1])) / 2 : (Number(S.box[k][0]) + Number(S.box[k][1])) / 2;
  const thin = Object.fromEntries(BOX6.map((k) => [k, [mid[k], mid[k]]]));
  const p = cl.params, Qd = p.Q ? F.dec(p.Q) : null;
  let val;
  if (m[1] === 'P') val = F.wellhead(thin, Qd, F.dec(p.Pd)).P;
  else if (m[1] === 'v') val = F.kinematics(thin, Qd).v;
  else if (m[1] === 'Re') val = F.kinematics(thin, Qd).Re;
  else if (m[1] === 'claim' && m[3] === 'ceiling') { const c = I.add(F.dec(p.Pd), I.div(I.mul(I.mul(I.iv(mid.rho), F.dec('9.80665')), I.iv(mid.dz)), I.iv(1e5))); const cv = F.dec(p.claim); val = I.sub(cv, c); return { at: mid, value: val, status: val[1] <= 0 ? 'witness' : val[0] > 0 ? 'delta artifact' : 'undecided', of: 'claim − ceiling at the midpoint' }; }
  else return null;
  const c = Number(p[m[3]]), op = m[2];
  if (op === '==') return { at: mid, value: val, status: 'equality (a point cannot prove it)', of: m[1] + ' at the midpoint against ' + c };
  const holds = op === '>' ? val[0] > c : op === '>=' ? val[0] >= c : op === '<' ? val[1] < c : val[1] <= c;
  const fails = op === '>' ? val[1] <= c : op === '>=' ? val[1] < c : op === '<' ? val[0] >= c : val[0] > c;
  const inBox = BOX6.every((k) => !box[k] || (mid[k] >= Number(S.box[k][0]) && mid[k] <= Number(S.box[k][1])));
  return { at: mid, value: val, status: holds ? 'witness' : fails ? 'delta artifact' : 'undecided', of: m[1] + ' ' + op + ' ' + c + ' at the midpoint', inDeclaredBox: inBox };
}
const KLEENE = (ws) => (ws.includes('REFUTADO') ? 'REFUTADO' : ws.includes('RECUSADO') ? 'RECUSADO' : 'PROVADO');
const TO_GATE = (cl, w) => (w === 'REFUTED' ? 'REFUTADO' : (w === 'CERTIFIED' || w === 'CONSISTENT' || w === 'HOLDS') ? 'PROVADO' : 'RECUSADO');

function derive(C, run) {
  need(run.claimsSha256 === shaBuf(fs.readFileSync(abs(CLAIMS))), 'the run decided another claims file');
  const byKey = new Map(run.results.map((r) => [r.claim + '|' + r.query + '|' + r.delta, r]));
  const claims = [], words = {};
  for (const cl of C.claims) {
    const ours = oursWord(cl), row = { id: cl.id, family: cl.family, kind: cl.kind, statement: cl.statement, ours, dreal: {}, agree: {} };
    if (cl.object) row.object = cl.object;
    if (cl.encodable === false) { row.encodable = false; row.why = cl.why; for (const d of C.deltas) { row.dreal[d] = { word: 'NO FORMULA' }; row.agree[d] = 'door'; } claims.push(row); continue; }
    for (const d of C.deltas) {
      const ans = {};
      for (const q of Object.keys(cl.queries)) {
        const r = byKey.get(cl.id + '|' + q + '|' + d);
        need(r, 'the run has no answer for ' + cl.id + ' ' + q + ' δ=' + d);
        const a = { answer: r.answer, solveSeconds: r.solveSeconds, buildSeconds: r.buildSeconds, wallSeconds: r.wallSeconds };
        if (r.error) a.error = r.error;
        if (r.box) { a.box = r.box; let w; try { w = witness(cl, q, r.box); } catch (e) { w = { status: 'the gate refused the midpoint: ' + String(e.message || e).slice(0, 120) }; } if (w) a.witness = w; }
        ans[q] = a;
      }
      const w = drealWord(cl, ans);
      row.dreal[d] = { word: w, seconds: Object.values(ans).reduce((s, a) => s + (a.solveSeconds || 0), 0), queries: ans };
      row.agree[d] = agreement(cl, ours, w);
      words[cl.id + '|' + d] = w;
    }
    claims.push(row);
  }
  const receipts = C.receipts.map((r) => {
    const out = { id: r.id, gate: r.gate, dreal: {}, agree: {} };
    for (const d of C.deltas) {
      const ws = r.checks.filter((k) => k.claim).map((k) => { const cl = C.claims.find((x) => x.id === k.claim); return TO_GATE(cl, words[k.claim + '|' + d]); });
      out.dreal[d] = KLEENE(ws); out.agree[d] = out.dreal[d] === r.gate;
    }
    out.checks = r.checks;
    return out;
  });
  const totals = {};
  for (const d of C.deltas) {
    const t = { claims: 0, agree: 0, 'dReal weaker': 0, 'dReal stronger': 0, contradiction: 0, door: 0, anomaly: 0, differ: 0, receipts: receipts.length, receiptsAgree: receipts.filter((r) => r.agree[d]).length, deltaArtifacts: 0, witnesses: 0 };
    for (const c of claims) { t.claims++; t[c.agree[d]]++; for (const a of Object.values((c.dreal[d] || {}).queries || {})) if (a.witness) { if (a.witness.status === 'delta artifact') t.deltaArtifacts++; if (a.witness.status === 'witness') t.witnesses++; } }
    totals[d] = t;
  }
  /* findings, derived from the answers — never written by hand */
  const findings = [];
  for (const c of claims) for (const d of C.deltas) {
    const a = c.agree[d];
    if (a === 'contradiction' || a === 'anomaly' || a === 'differ') findings.push({ kind: a, delta: d, claim: c.id, ours: c.ours, dreal: c.dreal[d].word, statement: c.statement });
    else if (a === 'dReal weaker' || a === 'dReal stronger') findings.push({ kind: a, delta: d, claim: c.id, ours: c.ours, dreal: c.dreal[d].word, statement: c.statement });
    else if (a === 'door') findings.push({ kind: 'door', delta: d, claim: c.id, ours: c.ours, dreal: c.dreal[d].word, statement: c.encodable === false ? c.why : 'a MALFORMED object: cert-machine refuses it at the door; dReal has no door and decides the formula as written' });
    for (const [q, an] of Object.entries((c.dreal[d] || {}).queries || {})) if (an.witness && an.witness.status === 'delta artifact') findings.push({ kind: 'delta artifact', delta: d, claim: c.id, query: q, at: an.witness.at, value: an.witness.value, statement: 'dReal\'s delta-sat box for "' + C.claims.find((x) => x.id === c.id).queries[q].join(' ∧ ') + '": at its midpoint the gate proves the atom false' });
    if (c.kind === 'precondition' && c.ours === 'REFUSED' && c.dreal[d] && c.dreal[d].word === 'REFUTED') findings.push({ kind: 'note', delta: d, claim: c.id, statement: 'dReal proves the precondition fails on ALL of the box (Re < 4000 everywhere); the gate declines the receipt, as it should, but its text says "parte da caixa não é turbulenta" (part of the box) — the printed Re range shows the whole box' });
  }
  return { claims, receipts, totals, findings };
}

