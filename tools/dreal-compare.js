const PI = ['3.141592653589793238462643383279502884197169399375', '3.141592653589793238462643383279502884197169399376'];
const LN10 = ['2.302585092994045684017991454684364207601101488628', '2.302585092994045684017991454684364207601101488629'];
function checkConstants() {
  const P = 70, S = 10n ** BigInt(P);
  /* atan(1/k)·S: alternating terms floored (error < 1 each) and a tail below the first omitted term (< 1) */
  const atan = (k) => { let s = 0n, n = 0n, pw = BigInt(k), sg = 1n; const k2 = BigInt(k * k); for (;;) { const t = S / ((2n * n + 1n) * pw); if (t === 0n) break; s += sg * t; sg = -sg; pw *= k2; n++; } return [s - n - 1n, s + n + 1n]; };
  /* atanh(1/k)·S: positive terms floored, tail below 9/8 of a term that floored to 0 */
  const atanh = (k) => { let s = 0n, n = 0n, pw = BigInt(k); const k2 = BigInt(k * k); for (;;) { const t = S / ((2n * n + 1n) * pw); if (t === 0n) break; s += t; pw *= k2; n++; } return [s, s + n + 2n]; };
  const a5 = atan(5), a239 = atan(239);
  const pi = [16n * a5[0] - 4n * a239[1], 16n * a5[1] - 4n * a239[0]];                 /* Machin */
  const l2 = atanh(3), l54 = atanh(9);                                                  /* ln 2 = 2 atanh(1/3), ln 5/4 = 2 atanh(1/9) */
  const ln10 = [6n * l2[0] + 2n * l54[0], 6n * l2[1] + 2n * l54[1]];                    /* ln 10 = 3 ln 2 + ln 5/4 */
  const scaled = (s) => { const [i, f = ''] = s.split('.'); return BigInt(i + f.padEnd(P, '0')); };
  need(scaled(PI[0]) < pi[0] && pi[1] < scaled(PI[1]), 'the π enclosure does not contain π');
  need(scaled(LN10[0]) < ln10[0] && ln10[1] < scaled(LN10[1]), 'the ln 10 enclosure does not contain ln 10');
}

/* ---------------------------------------------------------------- the formulas' names -- */
const FUNCS = new Set(['log', 'sqrt', 'exp', 'Max', 'Min', 'sum']);
const tokens = (s) => (s.match(/[A-Za-z_][A-Za-z_0-9]*/g) || []).filter((t) => !FUNCS.has(t));
/* keep only the vars, params and defs a claim's atoms reach (the runner would ignore the rest; the file stays legible) */
function minimal(c) {
  const seen = new Set(), stack = [];
  for (const a of [...c.given, ...Object.values(c.queries).flat()]) stack.push(...tokens(a));
  while (stack.length) { const t = stack.pop(); if (seen.has(t)) continue; seen.add(t); if (c.defs[t]) stack.push(...tokens(c.defs[t])); }
  const pick = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => seen.has(k)));
  for (const t of seen) need(c.vars[t] || c.params[t] || c.defs[t], c.id + ': unknown name ' + t);
  return { ...c, vars: pick(c.vars), params: pick(c.params), defs: pick(c.defs) };
}

