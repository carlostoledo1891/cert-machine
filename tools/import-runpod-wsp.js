#!/usr/bin/env node
/* import-runpod-wsp.js — bring Stage 3 of the Weight-Space Programming verification (tools/runpod-wsp-baseline.sh on one
   RunPod pod) to the desk: every finished condition's samples.jsonl.gz (every generated text, verified against the sha256
   the pod wrote in its meta.json) into corpus/wsp/.cache/baseline-runs/<pod>/<condition>/ (git-ignored, like the other
   2.5 GB of inputs) and the facts of the run — the pod's build line, each condition's meta (sampling, thinking, versions,
   GPU, seconds, tokens, the samples' sha256 and bytes) — into corpus/wsp/baseline-runs/<pod>.json (committed). Nothing is
   graded here: tools/wsp-baseline.py grades every text with instruments/wsp/grade.py and writes certs/wsp-baseline.json.
   usage: node tools/import-runpod-wsp.js <pod-id> [--partial]   (--partial: import the finished conditions of a pod that
                                                                   has not reached phase "complete") */
'use strict';
const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const crypto = require('crypto');
const pod = process.argv[2];
const partial = process.argv.includes('--partial');
if (!pod || !/^[a-z0-9]+$/.test(pod)) { console.error('usage: import-runpod-wsp.js <pod-id> [--partial]'); process.exit(2); }
const ROOT = path.join(__dirname, '..');
const BASE = 'https://' + pod + '-8000.proxy.runpod.net/';
const CACHE = path.join(ROOT, 'corpus', 'wsp', '.cache', 'baseline-runs', pod);
const OUT = path.join(ROOT, 'corpus', 'wsp', 'baseline-runs', pod + '.json');
const get = (rel) => { const r = cp.spawnSync('curl', ['-fsS', '--max-time', '120', BASE + rel], { encoding: 'utf8', maxBuffer: 1 << 28 }); return r.status === 0 ? r.stdout : null; };
const getFile = (rel, dst) => { const r = cp.spawnSync('curl', ['-fsS', '--max-time', '1800', '-o', dst, BASE + rel], { encoding: 'utf8' }); return r.status === 0 && fs.existsSync(dst); };
const sha = (p) => crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const st = JSON.parse(get('_status.json') || 'null');
if (!st) { console.error('no _status.json at ' + BASE); process.exit(1); }
console.log('pod ' + pod + ': ' + st.phase + ' (done:' + (st.done || ' none') + '; audit ' + st.audit + '; ' + st.updated + ')');
if (st.phase !== 'complete' && !partial) { console.error('not complete — pass --partial to import the finished conditions'); process.exit(3); }
const done = String(st.done || '').trim().split(/\s+/).filter(Boolean);
if (!done.length) { console.error('no finished condition'); process.exit(1); }
fs.mkdirSync(CACHE, { recursive: true });
const build = get('_build.txt');
for (const f of ['_status.json', '_build.txt', '_download.log']) { const b = get(f); if (b != null) fs.writeFileSync(path.join(CACHE, f), b); }
const conditions = {};
for (const c of done) {
  const meta = JSON.parse(get(c + '/meta.json') || 'null');
  if (!meta || !meta.samples_sha256) { console.error(c + ': no finished meta.json served'); process.exit(1); }
  const dir = path.join(CACHE, c); fs.mkdirSync(dir, { recursive: true });
  const dst = path.join(dir, 'samples.jsonl.gz');
  if (!fs.existsSync(dst) || sha(dst) !== meta.samples_sha256) {
    process.stdout.write(c + ': downloading samples.jsonl.gz … ');
    if (!getFile(c + '/samples.jsonl.gz', dst)) { console.error('download failed'); process.exit(1); }
    console.log((fs.statSync(dst).size / 1e6).toFixed(1) + ' MB');
  }
  const got = sha(dst);
  if (got !== meta.samples_sha256) { console.error(c + ': samples.jsonl.gz sha256 ' + got + ' ≠ the pod\'s ' + meta.samples_sha256 + '; not imported'); process.exit(1); }
  fs.writeFileSync(path.join(dir, 'meta.json'), JSON.stringify(meta, null, 1) + '\n');
  const log = get(c + '/_run.log'); if (log != null) fs.writeFileSync(path.join(dir, '_run.log'), log);
  conditions[c] = Object.assign({}, meta, { samples_bytes: fs.statSync(dst).size, samples_file: path.relative(ROOT, dst) });
  console.log(c + ': ' + meta.generations + ' generations, ' + meta.tokens_sum.toLocaleString('en-US') + ' tokens, cut share ' + meta.cut_share.toFixed(4) + ', ' + meta.seconds + ' s');
}
const run = { what: 'Stage 3 of the Weight-Space Programming verification: MATH-500 generated by the unedited Qwen/Qwen3.5-0.8B (and, in C4, the edited checkpoint) under the pre-registered conditions (notes/wsp-stage3-preregistration-2026-11-02.md) on one RunPod pod; the facts of the run — nothing graded here (tools/wsp-baseline.py)',
  pod: { id: pod, audit: st.audit, conditions_requested: st.conditions, deadline_hours: st.deadline_hours, status: st, build: build || null },
  imported: new Date().toISOString(), conditions };
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(run, null, 1) + '\n');
console.log(path.relative(ROOT, OUT) + ' written: ' + Object.keys(conditions).join(', ') + (st.phase === 'complete' ? '' : ' (PARTIAL: pod phase "' + st.phase + '")'));
