/* certified-evaluation.js — every number the pre-paper paper/tex/certified-evaluation.tex
   quotes, read from the records that decided it and written as LaTeX macros to
   paper/tex/certified-evaluation-numbers.tex. The paper \inputs that file, so it cannot
   quote a number the machine did not record; when a record no longer says what a
   sentence needs, this refuses (need()) instead of writing a stale macro — the
   pattern of tools/build-paper-numbers.js.

   Records read (never pages):
     certs/envs-record.json                the canary factory: corpus, graders, families,
                                           the uniformity gym, the attacker rungs, forgeries
     certs/erdos852-certificate.json       specimen I (the published C*), and the naive
                                           IEEE-754 product re-run live through
                                           instruments/erdos852/constants.js
     families/oeis-closedform.js + corpus/oeis-constants.json
                                           specimen II, the deepest exact impostor, re-derived
     families/ramanujan-audit.js           specimen III, the printed row and its correction
     instruments/sos/*.py                  the control (a published claim that held), run live
     certs/matmul-eval-ledger.jsonl, certs/matmul-eval-corrections.json,
     certs/matmul-loop-ledger.jsonl        the verified reward channel
     certs/gsm8k-ledger.json               GSM8K re-decided
     certs/horizon-ledger.json, corpus/metr-horizon/meta.json
                                           METR's time horizon certified
     certs/gym-record.json, certs/grader-pilot.json
                                           break-the-grader
     environments/blind_spot/pool/pool.json, certs/blind-spot-inspect-ledger.json
                                           blind-spot
     instruments/wiring/eval/{verifiers-*.json, page.json, rewire.json}
                                           lattice-claims
     certs/mathbench-ledger.jsonl          Certified MathBench v0
   Batteries that finish in seconds run here so their counts are live (envs, gsm8k,
   mathbench, the three SOS programs); the horizon battery takes over a minute and its
   count is read from the report's foot, as build-paper-numbers.js does for hseva.

   usage: node tools/paper-numbers/certified-evaluation.js                           MIT */
'use strict';
const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'paper', 'tex', 'certified-evaluation-numbers.tex');
const J = (rel) => JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8'));
const JL = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8').split('\n').filter((l) => l.trim()).map((l) => JSON.parse(l));
const die = (m) => { console.error('PAPER NUMBERS REFUSED: ' + m); process.exit(1); };
const need = (c, m) => { if (!c) die(m); };
const int = (x) => Math.round(Number(x)).toLocaleString('en-US').replace(/,/g, '{,}');
const dec = (x, d) => Number(x).toFixed(d);
const pct = (x, d) => (100 * Number(x)).toFixed(d) + '\\%';
const sgn = (x, d) => (x > 0 ? '+' : x < 0 ? '$-$' : '') + Math.abs(Number(x)).toFixed(d);
const sci = (x, d) => { const m = /^(-?[\d.]+)e([+-]?\d+)$/.exec(Number(x).toExponential(d)); return '$' + m[1] + '\\times10^{' + Number(m[2]) + '}$'; };
const git = (() => { try { return cp.execSync('git rev-parse --short=12 HEAD', { cwd: ROOT }).toString().trim(); } catch (e) { return 'unknown'; } })();
const tex = (s) => String(s).replace(/\\/g, '\\textbackslash{}').replace(/([&%$#_{}])/g, '\\$1').replace(/~/g, '\\textasciitilde{}').replace(/\^/g, '\\textasciicircum{}')
  .replace(/≥/g, '$\\ge$').replace(/≤/g, '$\\le$').replace(/→/g, '$\\to$').replace(/−/g, '$-$').replace(/×/g, '$\\times$').replace(/–/g, '--').replace(/—/g, '---').replace(/…/g, '\\ldots{}').replace(/"/g, "''");

const M = ['%% generated by tools/paper-numbers/certified-evaluation.js — do not edit (git ' + git + ')'];
const def = (name, val) => { if (!/^[A-Za-z]+$/.test(name)) die('bad macro name ' + name); M.push('\\newcommand{\\' + name + '}{' + val + '}'); };
const rows = (name, rr) => def(name, rr.map((r) => r.join(' & ') + ' \\\\').join('\n'));
function battery(cmd, args, re, what) {
  const r = cp.spawnSync(cmd, args, { cwd: ROOT, maxBuffer: 1 << 26 });
  const out = String(r.stdout) + String(r.stderr);
  const m = re.exec(out);
  if (r.status !== 0 || !m) die(what + ' did not pass clean:\n' + out.slice(-600));
  return { nums: m.slice(1).map(Number), out };
}
