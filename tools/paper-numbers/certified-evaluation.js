/* ================================================================ specimen II: the impostor */
{
  const OE = require(path.join(ROOT, 'families', 'oeis-closedform.js'));
  const K = { pi: Math.PI, e: Math.E, ln2: Math.LN2, ln10: Math.LN10, sqrt2: Math.SQRT2, sqrt3: Math.sqrt(3), sqrt5: Math.sqrt(5), phi: (1 + Math.sqrt(5)) / 2, euler: 0.5772156649015329 };
  function labelValue(label) {
    let mm;
    if ((mm = /^(\d+)\/(\d+)$/.exec(label))) return Number(mm[1]) / Number(mm[2]);
    if ((mm = /^sqrt\((\d+)\/(\d+)\)$/.exec(label))) return Math.sqrt(Number(mm[1]) / Number(mm[2]));
    if ((mm = /^cbrt\((\d+)\/(\d+)\)$/.exec(label))) return Math.cbrt(Number(mm[1]) / Number(mm[2]));
    if ((mm = /^\((\d+)\/(\d+)\)([a-z0-9]+)$/.exec(label))) return (Number(mm[1]) / Number(mm[2])) * K[mm[3]];
    if ((mm = /^([a-z0-9]+)\^\((\d+)\/(\d+)\)$/.exec(label))) return Math.pow(K[mm[1]], Number(mm[2]) / Number(mm[3]));
    return NaN;
  }
  function toRational(v) {
    if (!isFinite(v) || v <= 0) return null;
    let x = v, h0 = 0, h1 = 1, k0 = 1, k1 = 0;
    for (let i = 0; i < 12; i++) {
      const a = Math.floor(x); const h = a * h1 + h0, k = a * k1 + k0;
      h0 = h1; h1 = h; k0 = k1; k1 = k;
      if (k > 4096) break;
      if (Math.abs(v - h / k) <= 1e-13 * v) return [BigInt(h), BigInt(k)];
      const frac = x - a; if (frac < 1e-13) break; x = 1 / frac;
    }
    return null;
  }
  function agreementDepth(entryDigits, p, q) {
    let i = 0; while (i < entryDigits.length && entryDigits[i] === 0) i++;
    const ds = entryDigits.slice(i).join(''); const k = BigInt(ds.length); const D = BigInt(ds);
    let P = p, Q = q; while (P < Q) P *= 10n; while (P >= 10n * Q) Q *= 10n;
    const scale = 10n ** (k - 1n); const mid = P * scale;
    let gapN, gapD;
    if (mid < D * Q) { gapN = D * Q - mid; gapD = Q * scale; } else if (mid >= (D + 1n) * Q) { gapN = mid - (D + 1n) * Q; gapD = Q * scale; } else return Number(k);
    let d = 0; while (d < Number(k) + 10 && gapN * Q * (10n ** BigInt(d + 1)) <= P * gapD) d++;
    return d;
  }
  let deepest = 0, deepestId = null, deepestLabel = null, refutedCount = 0, entries = 0;
  for (let i = 0; ; i++) {
    const e = OE.enumerate(i); if (!e) break; entries++;
    if (!OE.interesting(e)) continue;
    const c = OE.certify(e); const x = c.extra;
    if (!x || !x.exactRefuted || !x.exactRefuted.length) continue;
    refutedCount += x.exactRefuted.length;
    for (const label of x.exactRefuted) {
      const r = toRational(labelValue(label)); if (!r) die('cannot re-derive rational for label ' + label);
      const d = agreementDepth(e.digits, r[0], r[1]);
      if (d > deepest) { deepest = d; deepestId = x.id; deepestLabel = label; }
    }
  }
  need(refutedCount === 21, 'expected 21 exact impostor refutations, found ' + refutedCount);
  need(deepest >= 60, 'the deepest impostor agreement fell below 60 digits: ' + deepest);
  const corpus = J('corpus/oeis-constants.json');
  const ent = corpus.entries.find((z) => z.id === deepestId);
  need(ent, 'the deepest impostor is not in the OEIS corpus');
  /* the depth routine ignores the power of ten, so 2/1 and 1/5 score alike; the paper names 1/5 (OEIS A271881 records the difference) and checks it here */
  need(agreementDepth(ent.digits, 1n, 5n) === deepest, 'the deepest impostor no longer agrees with 1/5 to the recorded depth (' + deepestLabel + ')');
  def('ImpostorCount', String(refutedCount)); def('ImpostorDepth', String(deepest)); def('ImpostorId', deepestId);
  def('ImpostorLabel', '1/5'); def('ImpostorName', tex(ent.name)); def('ImpostorPublishedDigits', String(ent.digits.length));
  def('OeisEntries', int(entries));
}

/* ================================================================ specimen III: true computation, false print */
{
  const RM = require(path.join(ROOT, 'families', 'ramanujan-audit.js'));
  let printed = 0, survive = 0, refuted = 0, printedRow = null, correctedRow = null;
  for (let i = 0; ; i++) {
    const o = RM.enumerate(i); if (!o) break;
    const c = RM.certify(o);
    if (/-corrected$/.test(o.id)) { if (o.id === 'rm-zo-z5z3b-corrected') correctedRow = c; continue; }
    printed++;
    if (c.verdict === 'HIT') survive++; else { refuted++; if (o.id === 'rm-zo-z5z3b-printed') printedRow = c; }
  }
  need(printed === 51, 'expected 51 printed Ramanujan Machine rows, found ' + printed);
  need(refuted === 1 && printedRow && printedRow.verdict === 'REJECT' && /sign slip/.test(printedRow.text), 'the RM printed-row refutation moved');
  need(correctedRow && correctedRow.verdict === 'HIT', 'the RM correction no longer certifies');
  def('RmPrinted', String(printed)); def('RmSurvive', String(survive)); def('RmRefuted', String(refuted));
  def('RmSheets', '7');
}

