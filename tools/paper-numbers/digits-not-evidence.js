/* paper-numbers/digits-not-evidence.js — every number the pre-paper
   "Digit agreement is not evidence: an impostor catalog of published constants
   refuted in exact arithmetic, and the Ramanujan Machine's printed sheets
   re-decided" quotes, read from the records that decided it and written as
   LaTeX macros:

     paper/tex/digits-not-evidence-numbers.tex
     paper/tex/fig/digits-not-evidence-{depth,widths}.pdf   (with --figs)

   Neither audit keeps a static certificate file: both report pages recompute
   their verdicts at build from the corpus and the family's own certifier, and
   so does this tool (each run takes about five seconds):
     families/oeis-closedform.js  over corpus/oeis-constants.json — the exact
       BigInt refutations, with the agreement depth re-derived here by the
       same definition tools/build-report-impostors.js uses
     families/ramanujan-audit.js  over the seven pinned sheets in
       corpus/sources/ (PINS.json) — all 52 rows re-certified, the tail bands
       re-proved, the constants re-bracketed by instruments/cf/minus.js and
       instruments/bigfloat/constants.js
     instruments/cf/battery.js    the instrument's gate, run live (seconds)
     ledger.json                  the engine's own counts, cross-checked
     tools/test-engine.js         the calibration list (read, not run)
     corpus/claims-seen.json      the sheets the Machine's results page lists
     pdftotext                    over the two 2018 sheets, to count their
                                  formula displays (poppler; refuses if absent)
   The paper \inputs the macro file, so it cannot quote a number no record holds;
   when a record no longer says what a sentence needs, this refuses (need()).

   usage: node tools/paper-numbers/digits-not-evidence.js [--figs]            MIT */
