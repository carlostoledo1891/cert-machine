  def('FormsTested', int(tested)); def('FormsUntested', int(OE.vocabulary - tested));
  def('DoubleRefuted', int(refutedDouble)); def('DoubleRefutedM', dec(refutedDouble / 1e6, 1));
  def('DoubleTestedTotal', int(tested * audited));
  def('OeisOnRecord', int(onRecord)); def('OeisHits', String(hits)); def('OeisOpen', String(open));
  def('ImpConstants', String(catalog.length)); def('ImpCount', String(impersonations));
  def('ImpDeepest', String(catalog[0].values[0].agree)); def('ImpShallowest', String(catalog[catalog.length - 1].values[0].agree));
