  const impRows = [];
  for (const e of catalog) for (const v of e.values) impRows.push(['\\texttt{' + e.id + '}', '$' + (v.q === 1n ? String(v.p) : '\\tfrac{' + v.p + '}{' + v.q + '}') + '$',
    v.spellings.map((s) => '\\texttt{' + tex(s) + '}').join(', '), String(v.prefix), String(v.agree), String(v.published), 'refuted']);
