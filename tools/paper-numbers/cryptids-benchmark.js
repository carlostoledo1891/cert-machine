#!/usr/bin/env node
/* paper-numbers/cryptids-benchmark.js — the numbers the method paper's claimbox VARIANT quotes
   (paper/tex/cert-machine-method.tex under \ifclaimbox): paper/tex/cryptids-benchmark-numbers.tex.

   Read from the records: certs/cryptids-benchmark.json (the two arms of the cryptids audit compared on the eight
   pre-registered metrics), certs/cryptids-audit.json (arm H), certs/claimbox-cryptids-decisions.json (arm C's words
   by the receiver), corpus/claimbox-cryptids/register-coverage.json and corpus/claimbox-riemann/records/recall.json (claimbox's grammar over
   the register's sentences and its planted-defect recall, copied from claimbox by LIFT-claimbox.json). A record that no
   longer supports a sentence refuses (need()), as every generator here does. Macros start with Cb.

   usage: node tools/paper-numbers/cryptids-benchmark.js                                                   MIT */
'use strict';
const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'paper', 'tex', 'cryptids-benchmark-numbers.tex');
const die = (m) => { console.error('CRYPTIDS BENCHMARK NUMBERS REFUSED: ' + m); process.exit(1); };
const need = (c, m) => { if (!c) die(m); };
const J = (rel) => { need(fs.existsSync(path.join(ROOT, rel)), 'missing ' + rel); return JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8')); };
const git = (() => { try { return cp.execSync('git rev-parse --short=12 HEAD', { cwd: ROOT }).toString().trim(); } catch (e) { return 'unknown'; } })();
const int = (x) => Math.round(Number(x)).toLocaleString('en-US').replace(/,/g, '{,}');
const M = ['%% generated by tools/paper-numbers/cryptids-benchmark.js from certs/cryptids-benchmark.json, certs/cryptids-audit.json, certs/claimbox-cryptids-decisions.json and the register coverage and recall copied from claimbox — do not edit (git ' + git + ')'];
const def = (name, val) => { if (!/^Cb[A-Za-z]+$/.test(name)) die('bad macro name ' + name); M.push('\\newcommand{\\' + name + '}{' + val + '}'); };

const B = J('certs/cryptids-benchmark.json');
const H = J('certs/cryptids-audit.json');
const D = J('certs/claimbox-cryptids-decisions.json');
const COV = J('corpus/claimbox-cryptids/register-coverage.json');
const REC = J('corpus/claimbox-riemann/records/recall.json');   /* claimbox's register recall, copied by the earlier lift item */
const K = fs.existsSync(path.join(ROOT, 'certs', 'cryptids-kernel.json')) ? J('certs/cryptids-kernel.json') : null;

need(B.M5.pairs >= 20 && B.M1.H.rows >= 20 && B.M1.C.written >= 20, 'the benchmark is thin: the kill switch');
need(H.summary.CERTIFIED + (H.summary.REFUTED || 0) + (H.summary.REFUSED || 0) === H.rows.length, 'arm H\'s words do not sum');
need(D.summary.CERTIFIED + (D.summary.REFUTED || 0) === D.rows.length, 'arm C\'s words do not sum');
need(COV.shaped + COV.refused === COV.sentences, 'the register coverage does not sum');

def('CbPin', String(B.target.commit).slice(0, 8));
def('CbDate', '2026-10-23');
/* arm H */
def('CbHRows', int(H.rows.length)); def('CbHCert', int(H.summary.CERTIFIED)); def('CbHRef', int(H.summary.REFUTED || 0)); def('CbHRefused', int(H.summary.REFUSED || 0));
def('CbHQuotes', int(B.M2.H.rowsWithQuote)); def('CbHQuotesVerbatim', int(B.M2.H.quotedVerbatim));
def('CbHRecall', int(B.M4.H.caught)); def('CbHRecallOf', int(B.M4.H.of));
def('CbHSeconds', String(Math.round(B.M6.H.seconds)));
def('CbHLines', int(Object.values(B.M6.H.lines).reduce((a, b) => a + b, 0)));
/* arm C */
def('CbCJobs', int(B.M1.C.jobs)); def('CbCWritten', int(B.M1.C.written)); def('CbCGrammarRefused', int(B.M1.C.refusedByGrammar));
def('CbCAdmitted', int(B.M1.C.admittedByChecker)); def('CbCCheckerRefused', int(B.M1.C.refusedByChecker.length));
def('CbCReceiverCert', int(D.summary.CERTIFIED)); def('CbCReceiverRef', int(D.summary.REFUTED || 0)); def('CbCReceiverRows', int(D.rows.length));
def('CbCFromObject', int(B.M1.C.written - D.rows.length));
need(typeof B.M4.C === 'object', 'arm C\'s recall is not in the benchmark');
def('CbCRecall', int(B.M4.C.caught)); def('CbCRecallOf', int(B.M4.C.of));
def('CbCLines', int(Object.values(B.M6.C.lines).reduce((a, b) => a + b, 0)));
const gr = B.M1.C.grammarRefusals;
def('CbCRefUnbounded', int(gr.unbounded || 0)); def('CbCRefAmbiguous', int(gr.ambiguous || 0)); def('CbCRefDecider', int(gr.decider || 0));
/* the comparison */
def('CbPairs', int(B.M5.pairs)); def('CbAgree', int(B.M5.agree)); def('CbDisagree', int(B.M5.disagree.length));
def('CbHOnly', int(B.M5.hOnly.length)); def('CbCOnly', int(B.M5.cOnly.length));
def('CbGaps', int(B.M8.length));
need(B.M5.disagree.length === 4, 'the paper describes four disagreements; the record has ' + B.M5.disagree.length);
need(B.secondImplementations.C && B.secondImplementations.C.disagree === 0, 'tm.py and tm.js disagree');
/* the register, through claimbox */
def('CbRegSentences', int(COV.sentences)); def('CbRegShaped', int(COV.shaped)); def('CbRegRefused', int(COV.refused));
def('CbRegNoQuantity', int(COV.byRefusal['no-quantity'] || 0)); def('CbRegProse', int(COV.byRefusal.prose || 0)); def('CbRegAsymptotic', int(COV.byRefusal.asymptotic || 0));
const plants = REC.plants !== undefined ? REC.plants : (REC.results || REC.rows || []).length;
const caught = REC.caught !== undefined ? REC.caught : (REC.results || REC.rows || []).filter((r) => r.caught || r.ok).length;
need(plants > 0, 'the register recall has no plants');
def('CbRegPlants', int(plants)); def('CbRegCaught', int(caught));
/* the kernel lane */
if (K) {
  def('CbKernelConfigs', int(K.rows.length));
  def('CbKernelTheorems', int(K.rows.reduce((s, r) => s + (r.theorems || 0), 0)));
  def('CbKernelWords', K.rows.map((r) => r.config.replace('_', '\\_') + ': ' + r.verdict).join(', '));
  def('CbKernelNanoda', K.rows.every((r) => r.nanodaAnswered) ? 'Lean\'s kernel and nanoda' : 'Lean\'s kernel');
}
fs.writeFileSync(OUT, M.join('\n') + '\n');
console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + (M.length - 1) + ' macros)');
