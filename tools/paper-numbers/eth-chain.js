#!/usr/bin/env node
/* paper-numbers/eth-chain.js — the numbers the note on Anthropic's ETH refutation carried to a standard multitape Turing
   machine (paper/tex/eth-chain.tex) quotes: paper/tex/eth-chain-numbers.tex. Read from certs/eth-chain.json,
   eth-c2.json, eth-c1.json, eth-comparator.json, eth-cslib-d1.json, eth-hawkley-heavy.json, eth-hawkley-bridge.json and
   eth-kernel.json; a record that no longer supports a sentence makes this refuse (need()).

   usage: node tools/paper-numbers/eth-chain.js                                                                        MIT */
'use strict';
const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'paper', 'tex', 'eth-chain-numbers.tex');
const die = (m) => { console.error('ETH CHAIN NUMBERS REFUSED: ' + m); process.exit(1); };
const need = (c, m) => { if (!c) die(m); };
const J = (rel) => { need(fs.existsSync(path.join(ROOT, rel)), 'missing record ' + rel); return JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8')); };
const git = (() => { try { return cp.execSync('git rev-parse --short=12 HEAD', { cwd: ROOT }).toString().trim(); } catch (e) { return 'unknown'; } })();
const M = ['%% generated by tools/paper-numbers/eth-chain.js from certs/eth-{chain,c2,c1,comparator,cslib-d1,hawkley-heavy,hawkley-bridge,kernel}.json — do not edit (git ' + git + ')'];
const def = (name, val) => { if (!/^Ec[A-Za-z]+$/.test(name)) die('bad macro name ' + name); M.push('\\newcommand{\\' + name + '}{' + val + '}'); };
const int = (x) => Math.round(Number(x)).toLocaleString('en-US').replace(/,/g, '{,}');

const ch = J('certs/eth-chain.json'), c2 = J('certs/eth-c2.json'), c1 = J('certs/eth-c1.json'), cm = J('certs/eth-comparator.json');
const d1 = J('certs/eth-cslib-d1.json'), hkh = J('certs/eth-hawkley-heavy.json'), hk = J('certs/eth-hawkley-bridge.json'), kn = J('certs/eth-kernel.json');
for (const [k, r] of Object.entries({ chain: ch, c2, c1, comparator: cm, d1 })) need(r.verdict === 'CERTIFIED', k + ' is not CERTIFIED');
need(hkh.word === 'CERTIFIED' && hk.word === 'CERTIFIED', 'Hawkley\'s chain is not CERTIFIED');
for (const [k, r] of Object.entries({ chain: ch, c2, c1 })) need(Object.values(r.planted).every((p) => p.refused) && Object.keys(r.planted).length === 3, k + ': not three planted variants, all refused');
const STD = ['propext', 'Classical.choice', 'Quot.sound'];
for (const [k, r] of Object.entries({ chain: ch, c2, c1 })) need(Object.values(r.axioms).every((a) => a && a.length === 3 && a.every((x) => STD.includes(x))), k + ': an axiom outside the three standard ones');
need(ch.judge.claim.okay && ch.judge.claim.accepted.length === 6 && !ch.judge.planted.okay, 'the chain\'s judge did not accept with six checkers, or the planted statement passed');
need(['c1', 'c2'].every((k) => cm.claims[k].verdict === 'CERTIFIED' && cm.claims[k].planted.rejected), 'the judge on C1/C2 is not whole');
const ant = kn.rows.find((r) => r.theorems.includes('MainResults.ethIsFalse')); need(ant && ant.word === 'CERTIFIED', 'Anthropic\'s own replay is not CERTIFIED');

def('EcChainNanoda', int(ch.nanoda.claim.declarations)); def('EcChainJudgeDecls', int(ch.judge.claim.declarations));
def('EcCtwoNanoda', int(c2.nanoda.claim.declarations)); def('EcConeNanoda', int(c1.nanoda.claim.declarations));
def('EcDoneNanoda', int(d1.nanoda.not_eth.declarations));
def('EcCtwoJudgeDecls', int(cm.claims.c2.judged.declarations)); def('EcConeJudgeDecls', int(cm.claims.c1.judged.declarations));
def('EcChainBuildMin', int(ch.steps.buildSeconds / 60)); def('EcChainFreshMin', int(ch.steps.leancheckerSeconds / 60));
def('EcPortFiles', int(ch.claim.port.files)); def('EcPortSame', int(ch.claim.port.byteIdentical)); def('EcPortEdited', int(ch.claim.port.modified));
def('EcClaimboxChain', ch.claim.commit.slice(0, 7)); def('EcClaimboxCtwo', c2.claim.commit.slice(0, 7)); def('EcClaimboxCone', c1.claim.commit.slice(0, 7));
def('EcComplexitylib', '7c66eb71'); def('EcDoneCommit', d1.claim.commit.slice(0, 8));
def('EcAnthropicCommit', ant.commit.slice(0, 8)); def('EcAnthropicLean', ant.toolchain.replace('leanprover/lean4:', ''));
def('EcMainResultsSha', ch.statement.mainResults.sha256.slice(0, 16));
def('EcChainPinSha', ch.statement.sha256.slice(0, 16)); def('EcCtwoPinSha', c2.statement.sha256.slice(0, 16)); def('EcConePinSha', c1.statement.sha256.slice(0, 16));
def('EcPlanted', int(Object.keys(ch.planted).length + Object.keys(c2.planted).length + Object.keys(c1.planted).length));
def('EcCommit', git);
fs.writeFileSync(OUT, M.join('\n') + '\n');
console.log('paper/tex/eth-chain-numbers.tex: ' + (M.length - 1) + ' macros');
