#!/usr/bin/env node
/* paper-numbers/cert-machine-method.js — the numbers the method paper (paper/tex/cert-machine-method.tex)
   quotes that no companion paper already writes: paper/tex/cert-machine-method-numbers.tex.

   Everything else the method paper quotes is \input from the companion papers' own macro files
   (register, p1, p2, ec-benchmark, delta3), so one record cannot say one thing there and another here.
   What is counted here is the system itself: the batteries the control build runs (read from
   tools/build-control.js, the list the build executes, not from prose) and the second
   implementations that share no code, each named by its file on disk. A file that is gone, or a
   list that no longer parses, makes this refuse (need()), as tools/build-paper-numbers.js does.

   usage: node tools/paper-numbers/cert-machine-method.js                                    MIT */
'use strict';
const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'paper', 'tex', 'cert-machine-method-numbers.tex');
const die = (m) => { console.error('METHOD PAPER NUMBERS REFUSED: ' + m); process.exit(1); };
const need = (c, m) => { if (!c) die(m); };
const exists = (rel) => fs.existsSync(path.join(ROOT, rel));
const git = (() => { try { return cp.execSync('git rev-parse --short=12 HEAD', { cwd: ROOT }).toString().trim(); } catch (e) { return 'unknown'; } })();

const M = ['%% generated by tools/paper-numbers/cert-machine-method.js from tools/build-control.js and the files it names — do not edit (git ' + git + ')'];
const def = (name, val) => { if (!/^Mt[A-Za-z]+$/.test(name)) die('bad macro name ' + name + ' (the method paper\'s own macros start with Mt)'); M.push('\\newcommand{\\' + name + '}{' + val + '}'); };

/* ---- the batteries the control build runs ----------------------------------- */
const src = fs.readFileSync(path.join(ROOT, 'tools', 'build-control.js'), 'utf8');
const a = src.indexOf('const BATTERIES = [');
const b = src.indexOf('const PY = [');
need(a > 0 && b > a, 'tools/build-control.js no longer declares BATTERIES and PY in that order');
const end = src.indexOf('\n];', b);
need(end > b, 'the PY list of tools/build-control.js does not close');
/* a row is a line that opens with ['name', ['file', ...] — the file must exist, or the build that runs it would fail */
const rows = (seg) => [...seg.matchAll(/^\s*\['((?:[^'\\]|\\.)+)',\s*\[([^\]]*)\]/gm)].map((m) => {
  /* the argv may open with flags (-m pytest, -u): the battery's file is the first argument that names a path */
  const argv = [...m[2].matchAll(/'([^']*)'/g)].map((x) => x[1]);
  return { name: m[1], file: argv.find((x) => /\//.test(x) || /\.(m?js|py)$/.test(x)) };
});
const node = rows(src.slice(a, b)), py = rows(src.slice(b, end));
need(node.length > 50 && py.length > 20, 'the battery lists parsed to ' + node.length + ' and ' + py.length + ' rows — the format moved');
for (const r of node.concat(py)) need(r.file && exists(r.file.split('::')[0]), 'the control build row ' + r.name + ' runs ' + r.file + ', which is not on disk');
def('MtBatteries', String(node.length + py.length));
def('MtBatteriesNode', String(node.length));
def('MtBatteriesPy', String(py.length));

/* ---- second implementations that share no code (each named by its file) -------- */
const SECOND = [
  ['abatimento', 'apps/abatimento/engine/reference.py'],
  ['contraprova', 'apps/contraprova/gate/reference.py'],
  ['janela', 'instruments/window/verify/battery.py'],
];
for (const [n, f] of SECOND) need(exists(f), 'the second implementation of ' + n + ' (' + f + ') is not on disk');
def('MtSecondImpls', String(SECOND.length));

const J = (rel) => { need(exists(rel), 'missing record ' + rel); return JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8')); };
const int = (x) => Math.round(Number(x)).toLocaleString('en-US').replace(/,/g, '{,}');

/* the abatement kernel against its Python reference: versions agreeing character for character, interior points */
const AB = J('apps/abatimento/data/registro-ledger.json').battery;
need(AB && AB.fail === 0 && AB.fired === AB.reds && AB.refVersions > 0 && AB.interior > 0, 'the abatement ledger does not record a clean battery with its reference agreement');
def('MtAbatVersions', String(AB.refVersions));
def('MtAbatInterior', int(AB.interior));

/* delta3: the claimant's verifier and the clean-room one, every certificate VERIFIED */
const D3 = J('certs/delta3-ledger.json');
need(D3.certificates.length > 0 && D3.certificates.every((c) => c.verdict === 'VERIFIED'), 'a delta3 certificate is not VERIFIED');
def('MtDeltaCerts', String(D3.certificates.length));

/* the zeta(7)/Catalan Hankel wall: rows re-run and bit-identical, the standard-library cross-check */
const ZH = J('certs/zeta-hankel-ledger.json').counts;
need(ZH && ZH.rowsRerun > 0 && ZH.bitIdentical === ZH.rowsRerun && ZH.crosscheckAgree === ZH.crosscheck, 'the zeta-Hankel ledger does not record every re-run row bit-identical');
def('MtZetaRows', String(ZH.rowsRerun));
def('MtZetaCross', String(ZH.crosscheck));

/* the rerun kit: its commands, and the one recorded execution */
const KIT = J('corpus/rerun-kit.json').entries;
const kitCommands = KIT.reduce((s, e) => s + ['rederive', 'verifier', 'second'].filter((k) => e[k]).length, 0);
need(kitCommands > 0, 'the rerun kit lists no command');
def('MtKitCommands', String(kitCommands));
const RUN = J('certs/rerun-kit-run.json');
need(RUN.partial === false && Array.isArray(RUN.runs) && RUN.runs.length > 0, 'the rerun kit run is partial or empty');
need(Array.isArray(RUN.rowsMoved) && Array.isArray(RUN.failed), 'the rerun kit run no longer lists moved rows and failures');
def('MtRunCommands', String(RUN.runs.length));
def('MtRunRows', String(RUN.registerRows));
def('MtRunMoved', String(RUN.rowsMoved.length));
def('MtRunFailed', String(RUN.failed.length));
def('MtRunDate', RUN.date);
def('MtRunMinutes', String(Math.round(RUN.runs.reduce((s, r) => s + r.seconds, 0) / 60)));

/* outside reruns: parties with no shared code who re-derived a record of this project */
const EXT = J('corpus/external-reruns.json');
need(Array.isArray(EXT) && EXT.length > 0, 'no outside rerun is recorded');
def('MtOutsideReruns', String(EXT.length));

def('MtCommit', git);
fs.writeFileSync(OUT, M.join('\n') + '\n');
console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + (M.length - 1) + ' macros)');
