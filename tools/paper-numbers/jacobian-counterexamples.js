/* paper-numbers/jacobian-counterexamples.js — every number the pre-paper
   "Explicit counterexamples to the Jacobian and Hessian conjectures, and weak
   Markus–Yamabe fields, decided in exact rational arithmetic" quotes, read from
   the records that decided it and written as LaTeX macros:

     paper/tex/jacobian-counterexamples-numbers.tex

   Records read:  certs/keller-certificate.json      the eleven detached certificates
                  certs/polymaps-ledger.json         Gao's maps and the Markus–Yamabe fields
                  corpus/polymaps/{meta,maps,witnesses}.json and the two pinned TeX sources
                  corpus/sources/PINS.json           the byte pins of the keller sources
   Live, because each runs in seconds (the pattern of tools/build-paper-numbers.js):
                  python3 tools/verify_keller.py     the stdlib verifier over the certificate
                  node instruments/keller/battery.js the instrument's gate (its red controls)
                  python3 instruments/polymaps/battery.py
                  families/keller-fibers.js          the blind fiber family (about ten seconds)
   The paper \inputs the macro file, so it cannot quote a number no record holds;
   when a record no longer says what a sentence needs, this refuses (need()).

   usage: node tools/paper-numbers/jacobian-counterexamples.js                    MIT */
