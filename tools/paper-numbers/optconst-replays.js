#!/usr/bin/env node
/* paper-numbers/optconst-replays.js — the numbers the registry use-case paper (paper/tex/optconst-replays.tex)
   quotes that the method paper's macro file does not already write: paper/tex/optconst-replays-numbers.tex.

   Everything else the paper quotes is \input from paper/tex/cert-machine-method-numbers.tex and register-numbers.tex,
   so one record cannot say one thing there and another here. What is written here is read from the records that
   decided the registry's rows — the pull-request queue (certs/optq-ledger.json), the step functions
   (certs/stepfun-replay.json), the autocorrelation rows (certs/autocorr-replay.json), the Zhang–Zagier rows
   (certs/c82-replay.json), the trace constant (certs/c86-replay.json), the truth table's second decision
   (certs/fei-second.json), the sums–differences ledger's side claims (certs/sumdiff-ledger.json), the planted claims
   (certs/method-eval.json) and the self-audit's entropy family (certs/selfaudit-mutations.json). A record that no
   longer says what a sentence of the paper needs makes this refuse (need()), as the other generators do. Macro names
   start with Oc.

   usage: node tools/paper-numbers/optconst-replays.js                                                           MIT */
'use strict';
const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const ROOT = path.resolve(__dirname, '..', '..');
const OUT = path.join(ROOT, 'paper', 'tex', 'optconst-replays-numbers.tex');
const die = (m) => { console.error('OPTCONST PAPER NUMBERS REFUSED: ' + m); process.exit(1); };
const need = (c, m) => { if (!c) die(m); };
const git = (() => { try { return cp.execSync('git rev-parse --short=12 HEAD', { cwd: ROOT }).toString().trim(); } catch (e) { return 'unknown'; } })();
const J = (rel) => { need(fs.existsSync(path.join(ROOT, rel)), 'missing record ' + rel); return JSON.parse(fs.readFileSync(path.join(ROOT, rel), 'utf8')); };
const M = ['%% generated by tools/paper-numbers/optconst-replays.js from the registry records named in its header — do not edit (git ' + git + ')'];
const def = (name, val) => { if (!/^Oc[A-Za-z]+$/.test(name)) die('bad macro name ' + name); M.push('\\newcommand{\\' + name + '}{' + val + '}'); };
const int = (x) => Math.round(Number(x)).toLocaleString('en-US').replace(/,/g, '{,}');
const esc = (t) => String(t).replace(/[&%$#_{}]/g, (c) => '\\' + c).replace(/—/g, '---').replace(/–/g, '--');
const con = (c) => '$' + String(c).replace(/^C_(\w+)$/, 'C_{$1}') + '$';
/* a printed bound as a table cell: the relation in math, the digits in text with a break point after the tenth, so an
   18-digit bound wraps inside its column instead of overflowing it */
const rel = (claim) => { const m = /^C_\w+ (<=|>=) (\S+)$/.exec(claim); need(m, 'an unexpected claim ' + claim);
  const d = m[2].length > 12 ? m[2].slice(0, 12) + '\\allowbreak ' + m[2].slice(12) : m[2];
  return '$' + (m[1] === '<=' ? '\\le' : '\\ge') + '$ ' + d; };
const quote = (t) => t.replace(/"([^"]*)"/g, "``$1''");
const hours = (sec) => (sec >= 3600 ? (sec / 3600).toFixed(1) + '~h' : sec >= 60 ? Math.round(sec / 60) + '~min' : Math.round(sec) + '~s');

/* ---- the pull-request queue of 2026-10-15 (certs/optq-ledger.json) ------------------------------------------------ */
{
  const Q = J('certs/optq-ledger.json');
  need(Q.counts.CERTIFIED === 9 && Q.counts.REFUTED === 0 && Q.counts.REFUSED === 1 && Q.rows.length === 10, 'the queue is not nine CERTIFIED and one REFUSED over ten rows');
  const OBJ = {
    'optq-225-1a': ['$C_{1a}$', '65{,}536-step function', 'the autoconvolution as one exact integer'],
    'optq-225-1b': ['$C_{1b}$', '114{,}688-step function', 'the correlation as one exact integer'],
    'optq-221-3c': ['$C_{3c}$', 'two laws, 51 and 47 points', 'exact pushforwards; entropies at 128 bits'],
    'optq-226-20a': ['$C_{20a}$', 'one-line construction', 'exact moments of the exponential law'],
    'optq-226-20c': ['$C_{20c}$', 'one-line construction', 'exact in $\\mathbb{Q}(\\sqrt3)$'],
    'optq-226-23b': ['$C_{23b}$', 'five-sentence argument', 'read, not computed: counted as a reading'],
    'optq-226-16a': ['$C_{16a}$', 'truncated lattice sums', 'fixed-point enclosures at $2^{200}$, from the author\'s derivation'],
    'optq-226-70a': ['$C_{70a}$', 'a Steiner sum', 'outward-rounded decimal recurrences, from the author\'s derivation'],
    'optq-217-28a': ['$C_{28a}$', 'a Lean development', 'this project\'s earlier two-kernel record, the statement read'],
    'optq-210-lambda': ['$\\Lambda$ (the registry\'s $C_{21a}$)', '104-file package', 'read file by file, nothing run'],
  };
  const word = (r) => (r.verdict === 'CERTIFIED' ? (/BY READING/.test(r.scope || '') ? 'a reading' : '\\vC') : r.verdict === 'REFUSED' ? '\\vF' : '\\vR');
  const rows = Q.rows.map((r) => { const o = OBJ[r.id]; need(o, 'the queue holds an unexpected row ' + r.id); return o[0] + ' & \\#' + r.pr + ' & ' + o[1] + ' & ' + word(r) + ' & ' + o[2]; });
  def('OcQueueRows', rows.join(' \\\\\n'));
  const reading = Q.rows.filter((r) => r.verdict === 'CERTIFIED' && /BY READING/.test(r.scope || ''));
  const earlier = Q.rows.filter((r) => r.id === 'optq-217-28a');
  need(reading.length === 1 && earlier.length === 1 && earlier[0].verdict === 'CERTIFIED' && /earlier record/.test(earlier[0].scope || ''), 'the queue\'s reading row and earlier-record row are not one each');
  def('OcQueueComputed', String(Q.counts.CERTIFIED - reading.length - earlier.length));
  def('OcQueueRead', String(reading.length)); def('OcQueueEarlier', String(earlier.length)); def('OcQueueRefused', String(Q.counts.REFUSED));
  def('OcQueueRegistryCommit', esc(String(Q.registryCommit).slice(0, 8)));
  const lam = Q.rows.find((r) => r.id === 'optq-210-lambda');
  need(lam && lam.verdict === 'REFUSED' && /not in the submission/.test(lam.scope), 'the package row is not the refusal the paper describes');
  def('OcLamScope', esc(lam.scope));
}

/* ---- the rows decided after the queue: step functions, autocorrelation, the Zhang–Zagier rows, the trace constant ---- */
{
  const S = J('certs/stepfun-replay.json'), A = J('certs/autocorr-replay.json'), Z = J('certs/c82-replay.json'), C = J('certs/c86-replay.json');
  need(S.counts.CERTIFIED === 4 && S.rows.length === 4 && S.rows.every((r) => r.agree && r.verdict === 'CERTIFIED'), 'the four step functions are not all CERTIFIED by two agreeing deciders');
  need(A.counts.CERTIFIED === 2 && A.counts.REFUTED === 1 && A.rows.every((r) => r.agree !== false), 'the autocorrelation record is not two CERTIFIED and one REFUTED');
  need(Z.rows.length === 2 && Z.rows.every((r) => r.verdict === 'CERTIFIED' && r.agree), 'the C_82 rows are not two CERTIFIED by two agreeing deciders');
  need(C.verdict === 'CERTIFIED' && C.agree === true && C.bound && C.bound.lePrinted === true, 'the C_86 certificate is not CERTIFIED at or below the printed bound by both deciders');
  const sfRow = (r) => { const prod = r.producer.replace(/ \(.*$/, ''); return con(r.constant) + ' & ' + esc(prod) + ' & ' + int(r.n) + '-step function & ' + rel(r.claim) + ' & \\vC, two programs'; };
  const a1c = A.rows.find((r) => r.id === '1c-rozetyp'), a1d = A.rows.find((r) => r.id === '1d-cert2026');
  need(a1c && a1c.verdict === 'CERTIFIED' && a1d && a1d.verdict === 'REFUTED' && a1d.stated && a1d.stated.fractionMatches && !/0$/.test(''), 'the autocorrelation rows moved');
  need(a1c.stated && a1c.stated.fractionMatches === true && a1c.stated.decimalMatches === false, 'the C_1c page no longer prints its fraction under a wrong decimal');
  const rows = S.rows.map(sfRow).concat([
    '$C_{1c}$ & ' + esc(a1c.producer.replace(/ \(.*$/, '')) + ' & ' + int(a1c.n) + '-step function & ' + rel(a1c.claim) + ' & \\vC, two programs',
    '$C_{1d}$ & pull request 224 & 300-cell step function & ' + rel(a1d.claim) + ' & \\vR\\ as printed; the repair \\vC, two programs',
    '$C_{82}$ & R.~Pinho & Doche\'s construction, $\\deg Q \\approx 10^9$ & ' + rel(Z.rows[0].claim) + ' & \\vC, two programs',
    '$C_{82}$ & the page\'s second construction & Doche\'s construction & ' + rel(Z.rows[1].claim) + ' & \\vC, two programs',
    '$C_{86}$ & R.~Pinho & step measure, 11 polynomials & ' + rel(C.claim) + ' & \\vC, two programs',
  ]);
  def('OcLaterRows', rows.join(' \\\\\n'));
  def('OcLaterCount', String(rows.length));
  def('OcSfSeconds', hours(S.seconds)); def('OcAcSeconds', hours(A.seconds)); def('OcAcPySeconds', String(Math.round(a1c.pySeconds)));
  def('OcAcReds', String(A.redControls.length)); need(A.redControls.every((r) => r.fired), 'an autocorrelation red control did not fire');
  def('OcAcPrintedDecimal', a1c.stated.decimal); def('OcAcExactDecimal', a1c.js.decimal.slice(0, 15)); def('OcAcFraction', a1c.js.value.replace('/', '/\\allowbreak '));
  need(a1d.js && a1d.js.value === a1d.stated.fraction, 'the C_1d exact value is not the certificate\'s own fraction');
  def('OcTraceCells', int(C.js.E1.cells)); def('OcTraceNonzero', int(C.js.E1.nonzeroCells)); def('OcTracePolys', String(C.js.E2.polynomials.length));
  def('OcTraceReds', String(C.redControls.length)); need(C.redControls.every((r) => r.fired), 'a trace-constant red control did not fire');
  def('OcTraceExact', esc(C.bound.exact).replace('/', '/\\allowbreak ')); def('OcTraceDecimal', C.bound.decimal.replace(/…$/, '').slice(0, 17));
  def('OcCzEpiPrinted', Z.rows[1].claim.replace(/^C_\w+ <= /, ''));
}

/* ---- the sums–differences ledger's side claims and the claimant's checker (certs/sumdiff-ledger.json) --------------- */
{
  const S = J('certs/sumdiff-ledger.json');
  need(Array.isArray(S.also) && S.also.length === 5 && S.observed && Array.isArray(S.observed.runs), 'the sums–differences ledger no longer carries its side claims and the checker observation');
  const alsoRows = S.also.map((a) => '$C_{' + a.of.replace('-95', '') + '}$ & ' + quote(esc(a.what)) + ' & $' + a.claim + '$ & ' + (a.verdict === 'CERTIFIED' ? '\\vC' : a.verdict === 'REFUTED' ? '\\vR' : '\\vF'));
  def('OcAlsoRows', alsoRows.join(' \\\\\n'));
  const runs = S.observed.runs; need(runs.length === 4 && runs.every((r) => r.printed === 'OK'), 'the checker observation is not four runs all printed OK');
  const WORD = { CERTIFIED: '\\vC', REFUTED: '\\vR', 'not certified': 'not \\vC' };
  const truthOf = (t) => { const m = /^(CERTIFIED|REFUTED|not certified)/.exec(t); need(m, 'an unexpected truth word in the checker observation: ' + t); return WORD[m[1]] + '{} here' + (/\(the certificate's own bound\)/.test(t) ? ' (its own bound)' : /58th decimal/.test(t) ? ' (above the certified end at the 58th decimal)' : /17th/.test(t) ? ' (above the ratio at the 17th significant digit)' : ''); };
  const show = (c) => (c.length > 24 ? '$' + c.slice(0, 15) + '\\ldots' + c.slice(-4) + '$' : '$' + c + '$');
  def('OcCheckerRows', runs.map((r) => show(r.claimed) + ' & OK & ' + truthOf(r.truth)).join(' \\\\\n'));
  def('OcCheckerDate', esc(/run on (\d{4}-\d\d-\d\d)/.exec(S.observed.what)[1]));
  def('OcCheckerDps', esc(/dps = (\d+)/.exec(S.observed.what)[1]));
  def('OcCbDenominatorDigits', String(S.rows[0].certificate.denominatorDigits));
  def('OcImprovementPrinted', esc(S.improvement.printed)); need(S.improvement.rounds === true, 'the registry\'s printed improvement no longer rounds from the enclosure');
}

/* ---- the truth table decided a second time (certs/fei-second.json) ------------------------------------------------ */
{
  const F = J('certs/fei-second.json');
  const p = F.plantedSummary; need(p.planted === p.fired && p.falseAccepted.length === 0 && p.trueRefuted.length === 0, 'a planted claim on the truth table was not decided as expected');
  def('OcFeiPlantedFalse', String(p.byTruth.FALSE)); def('OcFeiPlantedTrue', String(p.byTruth.TRUE)); def('OcFeiPlantedMalformed', String(p.byTruth.MALFORMED));
  const f = F.findingsAtPin; need(f && Array.isArray(f.pyWordDiffersFromReading), 'the truth table\'s second decision no longer records what it found at the pin');
  def('OcFeiFindingsAtPin', String(f.pyWordDiffersFromReading.length)); def('OcFeiFindingRefutedTrue', String(f.pyWordRefutesATrueClaim.length)); def('OcFeiFixedDate', f.fixed);
  need(F.agreement.every((a) => a.ok), 'the two truth-table deciders do not agree on every named check');
  def('OcFeiAgreementChecks', String(F.agreement.length));
  need(F.arb && F.arb.flint, 'the truth table\'s Arb comparison is not recorded'); def('OcFeiArbPrec', String(F.arb.prec));
}

/* ---- the planted claims on the three certificates and the self-audit's entropy family ----------------------------- */
{
  const E = J('certs/method-eval.json'); const ent = E.planted.rows.filter((r) => r.family === 'entropy');
  need(ent.length === 9 && ent.every((r) => r.correct), 'the planted entropy claims are not nine, all decided as expected');
  const cnt = (t) => ent.filter((r) => r.truth === t).length;
  def('OcEvFalse', String(cnt('FALSE'))); def('OcEvTrue', String(cnt('TRUE'))); def('OcEvMalformed', String(cnt('MALFORMED')));
  const S = J('certs/selfaudit-mutations.json'); const t = S.totals.entropy;
  need(t && t.falseCertifications === 0 && t.falseRefutations === 0 && t.malformedNotRefused === 0 && t.byOutcome['as required'] === t.mutants, 'the self-audit\'s entropy family is not all as required');
  def('OcSaRows', String(t.rows)); def('OcSaMutants', String(t.mutants)); def('OcSaFalse', String(t.byTruth.FALSE)); def('OcSaTrue', String(t.byTruth.TRUE)); def('OcSaMalformed', String(t.byTruth.MALFORMED));
  def('OcSaDate', S.generated.slice(0, 10));
}

def('OcCommit', git);
fs.writeFileSync(OUT, M.join('\n') + '\n');
console.log('wrote ' + path.relative(ROOT, OUT) + ' (' + (M.length - 1) + ' macros)');
