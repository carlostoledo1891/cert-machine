/* ================================================ Bakaryan et al., the Wardrop table */
(function wardrop() {
  const src = fs.readFileSync(path.join(ROOT, 'reports', 'verify_wardrop.py'), 'utf8');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mfg-redecided-wardrop-'));
  fs.writeFileSync(path.join(dir, 'verify_wardrop.py'), src);
  const r = cp.spawnSync('python3', ['verify_wardrop.py'], { cwd: dir, maxBuffer: 1 << 26 });
  fs.rmSync(dir, { recursive: true, force: true });
  const out = String(r.stdout) + String(r.stderr);
  need(r.status === 0 && /WARDROP REPRODUCTION: VERIFIED/.test(out), 'wardrop: the embedded verifier did not report VERIFIED:\n' + out.slice(-600));
  need(/S1 verdict: total CERTIFIED \+ split REFUSED/.test(out), 'wardrop: S1 verdict moved');
  need(/S2 verdict: CERTIFIED EXACTLY/.test(out), 'wardrop: S2 verdict moved');
  need(/S3 verdict: CERTIFIED \(existence \+ local uniqueness/.test(out), 'wardrop: S3 verdict moved');
  const grab = (re, what) => { const m = re.exec(out); need(m, 'wardrop: the verifier no longer prints the ' + what); return m; };
  const rad = grab(/unique KKT zero in a box of max radius ([\d.e+-]+)/, 'S3 box radius');
  const err = grab(/edge \(4,7\) total = (\d+)\/(\d+) = ([\d.]+)\s+-> rounds to (\d+)\s+\(Table 1 prints (\d+)/, 'erratum line');
  const dev = grab(/max deviation vs published Table 1 = (\d+)\/(\d+) = ([\d.]+)/, 'Table 1 deviation');
  const nul = grab(/DIMENSION (\d+)/, 'null-space dimension');
  const unk = grab(/n=(\d+) unknowns/, 'unknown count');
  const net = grab(/network: (\d+) nodes, (\d+) edges/, 'network size');
  const th = grab(/min inf theta = ([\d.]+)/, 'S3 flow floor');
  const sl = grab(/min inf slack = ([\d.]+)/, 'S3 slack floor');
  const reds = (out.match(/RED ok/g) || []).length; need(reds >= 6, 'wardrop: fewer than six falsifiers fired');
  def('WDBoxRadius', sci(Number(rad[1]), 2)); def('WDErratumFrac', frac(err[1] + '/' + err[2])); def('WDErratumValue', dec(Number(err[3]), 3)); def('WDErratumRounds', err[4]); def('WDPrinted', err[5]);
  def('WDMaxDevFrac', frac(dev[1] + '/' + dev[2])); def('WDMaxDev', dec(Number(dev[3]), 3)); def('WDNullDim', nul[1]); def('WDUnknowns', unk[1]);
  def('WDNodes', net[1]); def('WDEdges', net[2]); def('WDFlowFloor', dec(Number(th[1]), 4)); def('WDSlackFloor', dec(Number(sl[1]), 4)); def('WDReds', String(reds));
  def('WDVerifierSha', crypto.createHash('sha256').update(src).digest('hex').slice(0, 16)); def('WDVerifierKB', dec(src.length / 1024, 0));
})();

/* ==================================================== Gomes–Saúde, the clearing price */
(function price() {
  const PR = J('certs/price-band.json');
  pinned(PR, [[PR.provenance.code, PR.provenance.sha256], [PR.provenance.fd, PR.provenance.fdSha256], [PR.provenance.derive, PR.provenance.deriveSha256]], 'price');
  recheck('price');
  need(PR.verdict === 'PROVED', 'price: verdict is ' + PR.verdict);
  need(PR.exact.ladder.every((L) => L.certificate.verdict === 'PROVED'), 'price: a ladder certificate is not PROVED');
  const L0 = PR.exact.ladder[0]; need(L0.eta === '0', 'price: the first rung is not eta = 0');
  const N = PR.model.N, hour = (n) => dec(24 * n / N, 0);
  const th = /^(-?)(\d+)\/(\d+)$/.exec(PR.exact.theta.exact); need(th, 'price: Theta is not recorded as a rational');
  def('PRTheta', dec(PR.exact.theta.value, 6)); def('PRThetaExact', '$' + th[1] + '\\tfrac{' + th[2] + '}{' + th[3] + '}$');
  def('PREnergy', dec(PR.exact.energy.value, 6)); def('PRXiT', dec(PR.exact.XiT.value, 6)); def('PRxBar', dec(PR.exact.xbar0.value, 6));
  def('PRc', PR.model.c); def('PRGamma', PR.model.gamma); def('PRZeta', frac(PR.model.zeta)); def('PRN', String(N)); def('PRGridTimes', String(L0.certificate.evidence.gridTimes));
  const rho = /^(\d+)\/(\d+)$/.exec(PR.exact.rho); need(rho, 'price: rho is not a rational'); const rhoV = Number(rho[1]) / Number(rho[2]);
  def('PRRhoPct', dec(100 * rhoV, 0)); def('PRRhoFrac', frac(PR.exact.rho));
  def('PRWidest', dec(L0.maxWidth.value, 4)); def('PRWidestHour', hour(L0.maxWidth.at)); def('PRWidestExact', '$\\tfrac{' + L0.maxWidth.exact.split('/')[0] + '}{' + L0.maxWidth.exact.split('/')[1] + '}$');
  def('PRDayPart', dec(L0.maxWidth.parts.day, 4)); def('PRInstAtWidest', dec(L0.maxWidth.parts.inst, 4));
  def('PRInstMax', dec(Math.max(...L0.band.width) - L0.maxWidth.parts.day, 3));
  def('PRDayShare', dec(100 * L0.maxWidth.parts.day / L0.maxWidth.value, 0)); def('PRRhoForOne', dec(100 * rhoV / L0.maxWidth.value, 2)); def('PRWidthAtZero', dec(L0.widthAt0.value, 4));
  def('PRPiZero', dec(L0.Pi0.value, 4)); def('PRPiT', dec(L0.PiT.value, 4));
  rows('PRLadderRows', PR.exact.ladder.map((L) => [L.eta, frac(L.kappa), dec(L.maxWidth.value, 4), hour(L.maxWidth.at), dec(L.maxWidth.parts.inst, 3), dec(L.maxWidth.parts.day, 3), dec(L.maxWidth.parts.set, 3), dec(L.Pi0.value, 4), dec(L.PiT.value, 4)]));
  def('PRFalsifiers', String(L0.certificate.falsifier.length)); def('PREnergyLo', dec(L0.certificate.evidence.energyLo, 4)); def('PREnergyHi', dec(L0.certificate.evidence.energyHi, 4));
  /* the lab's kernel, measured */
  const F = PR.fdBox, E = PR.exact.energy.value;
  need(F.lab.converged && F.constrained.converged && F.consistent.converged, 'price: a kernel run did not converge');
  need(F.lab.lost > 0.08 && F.lab.lost < 0.09 && Math.abs(F.consistent.lost) < 1e-12, 'price: the kernel measurements moved');
  const NAMES = { lab: 'lab walls, control-cleared', constrained: 'constraint walls, control-cleared', consistent: 'constraint walls, flux-cleared' };
  rows('PRKernelRows', ['lab', 'constrained', 'consistent'].map((k) => [NAMES[k], dec(F[k].XiT, 4), Math.abs(F[k].lost) < 1e-9 ? sci(Math.abs(F[k].lost), 0) : dec(F[k].lost, 4), dec(F[k].PiMid, 3), dec(F.wallDensityT[k], 1), String(F[k].it), sci(F[k].res, 1)]));
  def('PRLabXiT', dec(F.lab.XiT, 4)); def('PRLabLost', dec(F.lab.lost, 4)); def('PRLabLostPct', dec(100 * F.lab.lost / E, 1)); def('PRConstrainedLost', dec(F.constrained.lost, 4));
  def('PRConsistentLost', sci(Math.abs(F.consistent.lost), 0)); def('PRLabClearGap', sci(F.lab.clearGap, 1)); def('PRLabIt', String(PR.lab.it)); def('PRLabRes', sci(PR.lab.res, 1));
  def('PRLabNX', String(PR.lab.NX)); def('PRLabNT', String(PR.lab.NT)); def('PRWallDensityLab', dec(F.wallDensityT.lab, 1));
  def('PRShadow', dec(L0.Pi0.value - F.consistent.PiMid, 3)); def('PRLabPiMid', dec(F.lab.PiMid, 3)); def('PRConsistentPiMid', dec(F.consistent.PiMid, 3));
  need(PR.wideRuns.order > 1.5 && PR.wideRuns.labOrder < 1, 'price: the convergence orders moved');
  def('PROrder', dec(PR.wideRuns.order, 2)); def('PRLabOrder', dec(PR.wideRuns.labOrder, 2)); def('PRWideA', String(PR.wide.xa)); def('PRWideB', String(PR.wide.xb));
  const W = PR.wideRuns;
  rows('PRWideRows', [['flux-cleared, constrained walls', dec(W.consistent[0].H, 4), W.consistent[0].NX + ' $\\times$ ' + W.consistent[0].NT, dec(W.consistent[0].maxErr, 4)],
    ['', dec(W.consistent[1].H, 4), W.consistent[1].NX + ' $\\times$ ' + W.consistent[1].NT, dec(W.consistent[1].maxErr, 4)],
    ["the lab's walls, control-cleared", dec(W.lab[0].H, 4), W.lab[0].NX + ' $\\times$ ' + W.lab[0].NT, dec(W.lab[0].maxErr, 4)],
    ['', dec(W.lab[1].H, 4), W.lab[1].NX + ' $\\times$ ' + W.lab[1].NT, dec(W.lab[1].maxErr, 4)]]);
  def('PRWideEtaErr', dec(W.consistentEta[0].maxErr, 4)); def('PRWideEta', String(W.consistentEta[0].eta));
  need(W.consistent[1].H < W.consistent[0].H && W.lab[1].H < W.lab[0].H, 'price: the wide runs are not ordered coarse to fine');
  def('PRWideErrCoarse', dec(W.consistent[0].maxErr, 4)); def('PRWideErrFine', dec(W.consistent[1].maxErr, 4));
  def('PRLabWideErrCoarse', dec(W.lab[0].maxErr, 4)); def('PRLabWideErrFine', dec(W.lab[1].maxErr, 4));
})();

/* ============================================ Alharbi–Ashrafyan–Gomes, the empty region */
(function aag() {
  const AA = J('certs/aag-empty-region.json');
  pinned(AA, [[AA.provenance.code, AA.provenance.sha256]], 'aag');
  recheck('aag');
  need(AA.verdict === 'VERIFIED' && AA.certificate.verdict === 'PROVED', 'aag: record is not VERIFIED/PROVED');
  const c1 = AA.case1, c2 = AA.case2, K = AA.options.K;
  need(c1.refusedOK && c1.rootsOK && c1.weak.ok && c2.mMin > 0, 'aag: a certificate condition is false');
  need(AA.roots.length === 3 && Math.abs(AA.roots[0] - 1 / 12) < 1e-12 && Math.abs(AA.roots[1] - 5 / 12) < 1e-12 && Math.abs(AA.roots[2] - 0.75) < 1e-12, 'aag: the roots are not 1/12, 5/12, 3/4');
  need(AA.ladder.every((l) => l.refused === 4 && Math.abs(l.refusedLength - 4 / l.K) < 1e-15), 'aag: the refused length is no longer 4/K on the ladder');
  def('AAGK', String(K)); def('AAGRefused', String(c1.refused)); def('AAGRefusedLength', String(c1.refusedLength));
  def('AAGLadderKs', AA.ladder.map((l) => l.K).join(', ')); def('AAGLadderFirstLength', String(AA.ladder[0].refusedLength)); def('AAGLadderLastLength', String(AA.ladder[AA.ladder.length - 1].refusedLength)); def('AAGLadderLastK', int(AA.ladder[AA.ladder.length - 1].K));
  rows('AAGRunsRows', c1.runs.map((r) => ['$[' + dec(r.x0, 5) + ',\\ ' + dec(r.x1, 5) + ')$', '\\textsc{' + r.standing.toLowerCase() + '}', r.standing === 'OCCUPIED' ? '$m = V$, enclosed on each cell' : r.standing === 'EMPTY' ? '$m = 0$ exactly' : 'holds a root of $V$ at this budget']));
  def('AAGEmptyRuns', String(c1.runs.filter((r) => r.standing === 'EMPTY').length)); def('AAGOccupiedRuns', String(c1.runs.filter((r) => r.standing === 'OCCUPIED').length));
  def('AAGuPlusZeroBox', box(c1.uPlus[0].slice(1), 4)); def('AAGuGapZero', dec(2 * c1.uPlus[0][1], 3));
  need(c1.uPlus[c1.uPlus.length - 1][1] === 0 && c1.uPlus[c1.uPlus.length - 1][2] === 0, 'aag: u+ is not exactly 0 at the exit');
  def('AAGGammaBox', '[' + c2.gamma.join(', ') + ']'); def('AAGCaseTwoFloor', floorTo(c2.mMin, 4)); def('AAGCaseTwoMax', ceilTo(c2.mMax, 4)); def('AAGjZero', frac('1/10'));
  def('AAGVOneBox', box(c1.boundary.V1, 4)); def('AAGmZeroBox', box(c1.boundary.m0, 4)); def('AAGExitFluxTwoBox', box(c2.boundary.noEntry.flux, 4));
  need(c1.boundary.contact.inContactSet && !c1.boundary.contact.exit && c2.boundary.contact.inContactSet && c2.boundary.contact.exit, 'aag: the contact-set verdicts moved');
  def('AAGFalsifiers', String(AA.certificate.falsifier.length));
})();

