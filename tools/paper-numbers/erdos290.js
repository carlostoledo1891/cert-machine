/* (ii) the horizon brute force would need, IF every further degree closes as the assumption
   predicts (hyperoctahedral, index-2 at 4k(k+1)): fixed-point BigInt, outward at every step */
{
  const SC = 10n ** 60n;
  const fl = (a) => { const q = a.n * SC; return q >= 0n ? q / a.d : -((-q + a.d - 1n) / a.d); };
  const ce = (a) => { const q = a.n * SC; return q >= 0n ? (q + a.d - 1n) / a.d : -(-q / a.d); };
  let pinLo = fl(sub(P0.lo, L2.lo)), pinHi = ce(sub(P0.hi, L2.hi));
  let partial = 0n; for (let l = 1; l <= Lmax; l++) partial += ce(W(l));
  const l2lo = fl(L2.lo), l2hi = ce(L2.hi);
  const oneMinusLog2Hi = SC - l2lo;
  let found = null, widthAt = null;
  for (let L = Lmax + 1; L <= 20000 && !found; L++) {
    /* δ_hyp(L) = 1 − Σ_{i≤L} (−1)^i/(2^i i!), truncated at i = 80 with the first omitted term as error */
    let s = 0n, f = 1n, term = SC, i = 0;
    const top = Math.min(L, 80);
    for (i = 0; i <= top; i++) { if (i > 0) f *= BigInt(i); term = SC / (2n ** BigInt(i) * f); s += (i % 2 === 0) ? term : -term; }
    const err = top < L ? SC / (2n ** BigInt(top + 1) * f * BigInt(top + 1)) + 1n : 1n;
    let dLo = SC - s - err, dHi = SC - s + err;
    if (isExcL(L)) { const al = (2n ** BigInt(L) * fact(L)); dLo -= (SC + al - 1n) / al; dHi -= SC / al; }
    const w = W(L); const wLo = fl(w), wHi = ce(w);
    pinLo += (dLo * wLo) / SC; pinHi += (dHi * wHi) / SC + 1n;
    partial += wHi;
    const tailHi = oneMinusLog2Hi - partial + BigInt(L) * 2n;           /* outward slack for the partial's rounding */
    const cLo = l2lo + pinLo, cHi = l2hi + pinHi + tailHi;
    const ivLo = (SC * SC) / (SC + cHi), ivHi = (SC * SC + SC + cLo - 1n) / (SC + cLo);
    const a = ivLo.toString().padStart(61, '0'), b = ivHi.toString().padStart(61, '0');
    let agreed = 0; for (let k = 1; k <= 12; k++) { if (a[k] === b[k]) agreed++; else break; }
    if (agreed >= 4) { found = L; widthAt = Number(cHi - cLo) / 1e60; }
  }
  need(found, 'no horizon under 20000 pins the fourth digit under the assumption');
  def('FourthL', int(found)); def('FourthD', int(2 * found)); def('FourthWidth', sci(widthAt, 2));
  def('FourthCost', int(Math.round(Math.pow(found / Lmax, 4))));
}

