/* ======================================================================= the fourth digit */
/* (i) the δ-window that would pin it at THIS horizon: the cell the conditional value sits in */
const cellLo = R(BigInt(dec(div(ONE, add(ONE, CS.hi)), 4, 'floor').replace('0.', '')), 10000n);
